-- The data API: what the gate is allowed to serve, and the keys that may ask
-- (docs/databases-plan.md 11.3, docs/studio-plan.md "catalog push").
--
-- These live in the GATE's schema, not the panel's, and that is the whole
-- design. The gate cannot read `panel.*` -- deploy/verify-panel.sh asserts it
-- on every install -- so it cannot be trusted to work out for itself what a
-- Resource exposes. Instead the panel PUSHES a finished catalog here, and the
-- gate serves exactly that and nothing else. No merge, no inference, no second
-- opinion: if a column is not in the catalog, the gate has never heard of it.
--
-- That is also why neither table references anything. `database_id` is the
-- panel's id for a database, carried across as a plain number, because a
-- foreign key into `panel.studio_databases` is not something the gate's role
-- could follow even if it existed. (It keeps S9 true for free: nothing here
-- reaches a ported table.)
--
-- Appended, never edited: tools/migrate.ts refuses a file whose checksum changed.

CREATE TABLE gate.studio_catalog (
  -- the panel's id for the database, and the only handle either side uses
  database_id bigint PRIMARY KEY,
  engine      text NOT NULL CHECK (engine IN ('postgres', 'mariadb')),
  name        text NOT NULL CHECK (name ~ '^[a-z][a-z0-9_]{0,62}$'),

  -- Both off until she says otherwise (docs/databases-plan.md, "defaults after
  -- Activate: control panel on, both API switches off"). Switching the app on
  -- does NOT put anything on the internet; these two do.
  api_read    boolean NOT NULL DEFAULT false,
  api_write   boolean NOT NULL DEFAULT false,

  -- The whole catalog for this database, as one document: per resource, its
  -- table, the columns it exposes, which of them identify a row, what may be
  -- searched and sorted, and which abilities are on (src/studio/catalog.ts).
  -- Replaced wholesale on every push.
  catalog_json text  NOT NULL,
  updated_at   bigint NOT NULL,

  UNIQUE (engine, name)
);

-- A key a program uses to reach her data. Like the form keys next door
-- (gate.api_keys): the key itself is never kept, only its hash.
CREATE TABLE gate.studio_app_keys (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  database_id  bigint NOT NULL,
  label        text NOT NULL,
  prefix       text NOT NULL,                  -- the first characters, to tell keys apart
  key_hash     text NOT NULL UNIQUE,           -- SHA-256; the key itself is never kept

  -- JSON: "all", or a list of resource table names. What the key MAY ask for.
  -- Never what it CAN do: that is clipped to the catalog on every request, so
  -- turning Delete off on the Resource refuses delete immediately, even for a
  -- key issued yesterday that still says write.
  grants       text NOT NULL DEFAULT '"all"',
  can_write    boolean NOT NULL DEFAULT false,

  created_at   bigint NOT NULL,
  created_by   text,
  last_used_at bigint,
  revoked_at   bigint,
  revoked_by   text
);

CREATE INDEX studio_app_keys_database ON gate.studio_app_keys (database_id) WHERE revoked_at IS NULL;
