-- What her tables MEAN, as opposed to how they are stored
-- (docs/databases-plan.md 11 and 15 `studio_resources` / `studio_fields`).
--
-- A table answers "how is this kept?". A Resource answers "what is this, and
-- what should people be able to do with it?". Nothing here is ever applied to
-- one of her databases: it is the panel's own overlay, and deleting all of it
-- would lose meaning, never data.
--
-- Rows rather than one JSON document, unlike `studio_drafts` and
-- `studio_layouts`. A draft is edited as a whole by one person at a desk; a
-- Resource definition is read a piece at a time by the generated pages and, in
-- a later slice, pushed to the gate as a catalog. §15 of the product plan
-- writes them as tables for that reason, and this follows it.
--
-- **Only what she has changed is stored.** Everything is inferred from the
-- schema every time the page loads (src/studio/resources.ts), so a row here is
-- an override, not a copy. That is what lets a new table appear as *proposed*
-- rather than silently arriving in her menu, and what stops the panel holding a
-- stale opinion about a column that has since changed type.
--
-- Types: plain `integer` is reserved in this schema for the yes/no flags the
-- SQLite era stored as 0/1 (test/pg.test.ts asserts every integer column is one
-- of them, by name). These tables are new and never lived in SQLite, so their
-- yes/no columns are real booleans -- which also lets `enabled` be NULL for
-- "she has not said", a third state an integer flag could not carry honestly.
-- `form_order` is a number rather than a flag, so it is bigint like every other
-- number here.
--
-- S9, until 2026-09-26: like 0004-0007, nothing here references a ported table.
--
-- Appended, never edited: tools/migrate.ts refuses a file whose checksum changed.

CREATE TABLE panel.studio_resources (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  database_id  bigint NOT NULL REFERENCES panel.studio_databases (id) ON DELETE CASCADE,
  -- the same rule the helper enforces, so no route can write a name down that
  -- the engine would refuse
  table_name   text NOT NULL CHECK (table_name ~ '^[a-z][a-z0-9_]{0,62}$'),

  -- Is this a thing she manages? NULL means "she has not said", which is not
  -- the same as "no": inference decides, and a new table stays proposed.
  enabled      boolean,

  -- Identity (§11.1). '' means "use what was inferred", so renaming a table
  -- does not leave her with a stale label she never typed.
  singular     text NOT NULL DEFAULT '',
  plural       text NOT NULL DEFAULT '',
  icon         text NOT NULL DEFAULT '',
  description  text NOT NULL DEFAULT '',

  -- Presentation. NULL/'' everywhere means inferred.
  title_field  text NOT NULL DEFAULT '',
  sort_field   text NOT NULL DEFAULT '',
  sort_dir     text NOT NULL DEFAULT 'asc' CHECK (sort_dir IN ('asc', 'desc')),

  -- Behavior (§11.1). CRUD is not all-or-nothing: an audit log she adopts can
  -- be View and Search only. These bind the generated pages AND the API (D11).
  can_create   boolean NOT NULL DEFAULT true,
  can_view     boolean NOT NULL DEFAULT true,
  can_edit     boolean NOT NULL DEFAULT true,
  can_delete   boolean NOT NULL DEFAULT true,
  can_duplicate boolean NOT NULL DEFAULT true,
  can_search   boolean NOT NULL DEFAULT true,
  can_sort     boolean NOT NULL DEFAULT true,
  can_filter   boolean NOT NULL DEFAULT false,

  -- D20: the engine's rule about deleting is the law; this is only whether she
  -- is shown the related counts first.
  on_delete    text NOT NULL DEFAULT 'follow' CHECK (on_delete IN ('follow', 'confirm')),

  UNIQUE (database_id, table_name)
);

-- One row per column she has said something about. A column with no row here
-- is exposed with its inferred label -- so adopting a database does not mean
-- filling in a form before anything works.
CREATE TABLE panel.studio_fields (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  database_id  bigint NOT NULL REFERENCES panel.studio_databases (id) ON DELETE CASCADE,
  table_name   text NOT NULL CHECK (table_name ~ '^[a-z][a-z0-9_]{0,62}$'),
  field_name   text NOT NULL CHECK (field_name ~ '^[a-z][a-z0-9_]{0,62}$'),

  -- The controlled window (§11.1). A column that is not exposed is not on the
  -- form, not in the list, and not in the API -- "existence in SQL is not
  -- permission to read or write".
  exposed      boolean NOT NULL DEFAULT true,
  label        text NOT NULL DEFAULT '',
  help         text NOT NULL DEFAULT '',
  -- how it is edited; '' means "work it out from the kind of field it is"
  control      text NOT NULL DEFAULT '',
  show_in_list boolean NOT NULL DEFAULT true,
  searchable   boolean NOT NULL DEFAULT false,
  filterable   boolean NOT NULL DEFAULT false,
  form_order   bigint NOT NULL DEFAULT 0,

  UNIQUE (database_id, table_name, field_name)
);
