-- What the panel remembers about the LOGINS on her engines
-- (docs/databases-plan.md 15 `studio_db_users`). The logins themselves live on
-- her Postgres and MariaDB and are listed by the helper; so does their access,
-- which is read back from the real GRANTs rather than kept here. Nothing in this
-- table is a privilege, and deleting a row takes nothing away from anyone.
--
-- All it holds is the note she writes next to a login -- "the recipes app on
-- port 3042" -- and when the panel made it, because an engine does not remember
-- either. A login the panel has forgotten still shows on the page: the live list
-- always wins, exactly as it does for databases.
--
-- No password is here, or anywhere in the panel. One is generated, shown to her
-- once and given to the engine (src/studio/users.ts); nothing keeps a copy, so
-- "she cannot see the old one" is a fact about the schema, not a rule the code
-- is asked to remember.
--
-- S9 still applies until 2026-09-26: nothing here references panel, media or
-- gate, so a rollback can still empty the ported tables (src/port.ts:241).
--
-- Appended, never edited: tools/migrate.ts refuses a file whose checksum changed.

CREATE TABLE panel.studio_db_users (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  engine     text NOT NULL CHECK (engine IN ('postgres', 'mariadb')),
  -- the same rule the helper enforces (src/pammydb/ident.ts NAME_RE), so no
  -- route can write down a name the engine would refuse
  name       text NOT NULL CHECK (name ~ '^[a-z][a-z0-9_]{0,62}$'),
  note       text NOT NULL DEFAULT '',
  created_at bigint NOT NULL,
  UNIQUE (engine, name)
);
