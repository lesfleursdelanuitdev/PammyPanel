-- Getting started (docs/getting-started-plan.md G1): the paths she started from
-- "What would you like to do?", and the little the site itself can't say.
--
-- Appended, never edited: tools/migrate.ts refuses a file whose checksum changed.
--
-- A step is done when the thing it asks for exists, so there is no "done"
-- column: the checks (src/getting-started/) read the site. What is kept here is
-- what she chose, what each path found and holds on to, a step she skipped or
-- ticked by hand, and whether the Home block is open.

-- One per path she started. Shared by the account managers: paths belong to the
-- website, and each says who started it (Q1).
CREATE TABLE panel.started_paths (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  path        text NOT NULL CHECK (path ~ '^[a-z][a-z0-9-]{0,40}$'),
  answers     text NOT NULL DEFAULT '{}',   -- JSON: what she answered, which picks the steps
  links       text NOT NULL DEFAULT '{}',   -- JSON: the database, form or folder it found, and any she said were not the one
  started_by  text NOT NULL,
  started_at  bigint NOT NULL,
  finished_at bigint,                       -- every step done or skipped, the last time the page looked
  put_away_at bigint                        -- "Put away": out of the list, kept for the record
);

-- Only where she said something: otherwise the step's check decides.
CREATE TABLE panel.path_steps (
  started_path_id bigint NOT NULL REFERENCES panel.started_paths (id) ON DELETE CASCADE,
  step            text NOT NULL CHECK (step ~ '^[a-z][a-z0-9-]{0,40}$'),
  state           text NOT NULL CHECK (state IN ('skipped', 'done-by-hand')),
  by              text NOT NULL,
  at              bigint NOT NULL,
  PRIMARY KEY (started_path_id, step)
);

-- The Home block, open or closed: per account, so it is the same on her phone.
ALTER TABLE panel.users ADD COLUMN getting_started_open boolean NOT NULL DEFAULT true;

-- Which example a database was copied from by "Make my own", the page that made,
-- and whether the sample records came too. Until now this was only an activity
-- line, which a check should not have to read.
ALTER TABLE panel.studio_databases ADD COLUMN copied_from text
  CHECK (copied_from IS NULL OR copied_from IN ('recipes', 'blog'));
ALTER TABLE panel.studio_databases ADD COLUMN page text;
ALTER TABLE panel.studio_databases ADD COLUMN copied_rows boolean NOT NULL DEFAULT false;

-- Copies made before this migration, from their activity lines:
--   target  "Postgres: my_recipes"
--   detail  "from the recipe book example, with 12 sample records; the page is kitchen/recipes.html"
-- (before refactor phase 6 it said "sample rows"; a copy without them has no "with").
UPDATE panel.studio_databases d
   SET copied_from = CASE WHEN a.detail LIKE 'from the recipe book example%' THEN 'recipes' ELSE 'blog' END,
       page        = substring(a.detail FROM '; the page is (.+)$'),
       copied_rows = a.detail ~ '^from the [a-z ]+ example, with '
  FROM (SELECT DISTINCT ON (target) target, detail FROM panel.activity
         WHERE action = 'database-example-copied' ORDER BY target, at DESC) a
 WHERE a.target = (CASE d.engine WHEN 'postgres' THEN 'Postgres' ELSE 'MariaDB' END) || ': ' || d.name
   AND (a.detail LIKE 'from the recipe book example%' OR a.detail LIKE 'from the blog example%');
