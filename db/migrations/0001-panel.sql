-- The panel's accounts, passkeys and sessions: panel.db as it stands at
-- user_version 3, table for table and column for column (docs/postgres-plan.md
-- P6). INTEGER -> bigint, 0/1 flags stay integer, BLOB -> bytea. Ids are
-- identities that take the ported ids as they are (P7).
--
-- Appended, never edited: tools/migrate.ts refuses a file whose checksum changed.

CREATE TABLE panel.users (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username         text NOT NULL UNIQUE,
  display_name     text NOT NULL,
  role             text NOT NULL CHECK (role IN ('manager', 'member')),
  active           integer NOT NULL DEFAULT 1,
  webauthn_user_id text NOT NULL UNIQUE,
  created_at       bigint NOT NULL,
  -- an account limited to one of her folders (docs/media-plan.md D22-D25); NULL: everything
  scope            text
);

-- A passkey keeps working only if credential_id, public_key (byte for byte),
-- counter and its user's webauthn_user_id come across unchanged.
CREATE TABLE panel.passkeys (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       bigint NOT NULL REFERENCES panel.users(id) ON DELETE CASCADE,
  credential_id text NOT NULL UNIQUE,
  public_key    bytea NOT NULL,
  counter       bigint NOT NULL,
  transports    text,
  device_type   text,
  backed_up     integer NOT NULL DEFAULT 0,
  name          text NOT NULL,
  created_at    bigint NOT NULL,
  last_used_at  bigint
);

CREATE TABLE panel.invites (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token_hash   text NOT NULL UNIQUE,
  user_id      bigint NOT NULL REFERENCES panel.users(id) ON DELETE CASCADE,
  created_by   bigint REFERENCES panel.users(id) ON DELETE SET NULL,
  created_at   bigint NOT NULL,
  expires_at   bigint NOT NULL,
  used_at      bigint,
  cancelled_at bigint
);

-- Removing a passkey ends the sessions it started (a lost phone stays logged out).
CREATE TABLE panel.sessions (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token_hash   text NOT NULL UNIQUE,
  user_id      bigint NOT NULL REFERENCES panel.users(id) ON DELETE CASCADE,
  passkey_id   bigint REFERENCES panel.passkeys(id) ON DELETE CASCADE,
  created_at   bigint NOT NULL,
  auth_at      bigint NOT NULL,
  last_seen_at bigint NOT NULL,
  expires_at   bigint NOT NULL,
  revoked_at   bigint,
  ip           text,
  user_agent   text
);
CREATE INDEX sessions_user ON panel.sessions(user_id);

CREATE TABLE panel.ceremonies (
  id_hash    text PRIMARY KEY,
  kind       text NOT NULL,
  challenge  text NOT NULL,
  user_id    bigint,
  invite_id  bigint,
  session_id bigint,
  expires_at bigint NOT NULL
);

CREATE TABLE panel.activity (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at          bigint NOT NULL,
  actor_id    bigint REFERENCES panel.users(id) ON DELETE SET NULL,
  actor_label text NOT NULL,
  action      text NOT NULL,
  target      text,
  detail      text,
  ip          text
);
CREATE INDEX activity_at ON panel.activity(at);

-- Who put a media file there, and when, for files added through the panel.
-- path: relative to her website; "trash:<id>/<name>" while in the trash.
CREATE TABLE panel.media_notes (
  path     text PRIMARY KEY,
  added_by text NOT NULL,
  added_at bigint NOT NULL,
  how      text NOT NULL CHECK (how IN ('uploaded', 'copied'))
);
