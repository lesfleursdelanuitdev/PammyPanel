-- What the panel remembers about HER databases (docs/databases-plan.md 15,
-- docs/studio-plan.md). Her databases, tables and rows live in her own engines
-- under svc-pammydb; nothing here is a copy of her data. This table is overlay:
-- which databases the panel looks after, and what it calls them. The live list
-- always comes from the helper, so a row here for a database she has since
-- dropped means "it's gone", not "it exists".
--
-- S9: while the cutover's reverse window is open (until 2026-09-26) nothing here
-- references panel, media or gate. A rollback leaves these rows in Postgres, and
-- re-running the port into the same database has to empty the ported tables
-- first, which src/port.ts:241 refuses if they hold rows -- a dependent foreign
-- key would make that emptying fail or cascade. So the engine and the name are
-- the identity, and no column points anywhere else.
--
-- Appended, never edited: tools/migrate.ts refuses a file whose checksum changed.

-- engine/name are spelled as her addresses spell them (databases-plan.md 13):
-- `postgres` and `mariadb`, matching src/pammydb/ident.ts.
CREATE TABLE panel.studio_databases (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  engine               text NOT NULL CHECK (engine IN ('postgres', 'mariadb')),
  -- the same rule the helper enforces (src/pammydb/ident.ts NAME_RE), written
  -- here too so no route can put a name in that the helper would refuse
  name                 text NOT NULL CHECK (name ~ '^[a-z][a-z0-9_]{0,62}$'),
  -- what her app is called ("Blog"); '' until she sets one
  display_name         text NOT NULL DEFAULT '',
  -- when the panel started looking after it, whether it made it or adopted it
  adopted_at           bigint NOT NULL,
  last_applied_at      bigint,
  last_introspect_json text,
  status               text NOT NULL DEFAULT 'inactive' CHECK (status IN ('inactive', 'active')),
  activated_at         bigint,
  api_read             integer NOT NULL DEFAULT 0,
  api_write            integer NOT NULL DEFAULT 0,
  UNIQUE (engine, name)
);

-- C18: the menu must never list two Blogs. Only active databases have to differ,
-- and only once a display name is set.
CREATE UNIQUE INDEX studio_databases_active_display_name
  ON panel.studio_databases (lower(display_name))
  WHERE status = 'active' AND display_name <> '';
