-- The media records, tags and categories: media.db as it stands at user_version 5
-- (docs/postgres-plan.md P6, docs/media-plan.md). INTEGER -> bigint, 0/1 flags
-- stay integer.
--
-- Two things SQLite did in its own dialect are written out for Postgres:
-- - its negative substr() (the last n characters) is right(), instr() is strpos();
-- - GLOB in the scope rules. "a file under this folder" was
--   `path GLOB folder || '/*'`, which misreads a folder whose name holds * ? or [
--   (media-api.ts says such names happen). Here it is media.path_under(), a plain
--   prefix test: what the GLOB meant.
--
-- Appended, never edited: tools/migrate.ts refuses a file whose checksum changed.

-- A label's scope '/' covers every file; '/olivia' covers olivia and everything in it.
CREATE FUNCTION media.path_under(label_scope text, path text) RETURNS boolean
  LANGUAGE sql IMMUTABLE PARALLEL SAFE
  RETURN label_scope = '/' OR path = substr(label_scope, 2) OR starts_with(path, substr(label_scope, 2) || '/');

-- One record per public file (D5): the scope and the name follow from the path.
CREATE TABLE media.media (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  path        text NOT NULL,              -- olivia/media/images/2026/dog.jpg (where it was, while trashed or missing)
  scope       text NOT NULL,              -- '/' or '/olivia'
  kind        text NOT NULL CHECK (kind IN ('images', 'files', 'audio', 'video', 'pages', 'other')),
  name        text NOT NULL,
  size        bigint NOT NULL,
  hash        text,                       -- sha256; NULL until worked out (or after the content changed)
  modified_at bigint NOT NULL,            -- the file's own modified time
  added_at    bigint NOT NULL,
  added_by    text,                       -- NULL when a sync found it
  how         text NOT NULL CHECK (how IN ('uploaded', 'copied', 'found')),
  state       text NOT NULL DEFAULT 'present' CHECK (state IN ('present', 'trashed', 'missing')),
  state_at    bigint,
  trash_id    text,                       -- the helper's trash id while trashed
  changed_at  bigint NOT NULL,            -- when this record last changed
  title       text,
  alt         text,
  CHECK (scope = CASE WHEN strpos(path, '/') = 0 THEN '/'
                      WHEN left(path, 6) = 'media/' THEN '/'
                      ELSE '/' || left(path, strpos(path, '/') - 1) END),
  CHECK (path = name OR right(path, length(name) + 1) = '/' || name),
  CHECK ((state = 'trashed') = (trash_id IS NOT NULL))
);
-- only one record per file that's there; one that went missing can share its old path
CREATE UNIQUE INDEX media_present_path ON media.media(path) WHERE state = 'present';
CREATE INDEX media_path ON media.media(path);
CREATE INDEX media_scope ON media.media(scope, kind, state);
CREATE INDEX media_trash ON media.media(trash_id) WHERE trash_id IS NOT NULL;

-- D10: names like form names; a scope is '/' or a folder path like '/olivia/trips'
CREATE TABLE media.tags (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scope      text NOT NULL,
  name       text NOT NULL,
  created_at bigint NOT NULL,
  created_by text,
  public     integer NOT NULL DEFAULT 0,
  CHECK (scope = '/' OR (length(scope) >= 2 AND left(scope, 1) = '/' AND right(scope, 1) <> '/' AND strpos(scope, '//') = 0)),
  CHECK (length(name) BETWEEN 1 AND 40 AND name !~ '[^a-z0-9-]'),
  UNIQUE (scope, name)
);
CREATE TABLE media.categories (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scope      text NOT NULL,
  name       text NOT NULL,
  created_at bigint NOT NULL,
  created_by text,
  public     integer NOT NULL DEFAULT 0,
  CHECK (scope = '/' OR (length(scope) >= 2 AND left(scope, 1) = '/' AND right(scope, 1) <> '/' AND strpos(scope, '//') = 0)),
  CHECK (length(name) BETWEEN 1 AND 40 AND name !~ '[^a-z0-9-]'),
  UNIQUE (scope, name)
);
CREATE TABLE media.media_tags (
  media_id bigint NOT NULL REFERENCES media.media(id) ON DELETE CASCADE,
  tag_id   bigint NOT NULL REFERENCES media.tags(id) ON DELETE CASCADE,
  PRIMARY KEY (media_id, tag_id)
);
CREATE TABLE media.media_categories (
  media_id    bigint NOT NULL REFERENCES media.media(id) ON DELETE CASCADE,
  category_id bigint NOT NULL REFERENCES media.categories(id) ON DELETE CASCADE,
  PRIMARY KEY (media_id, category_id)
);
CREATE INDEX media_tags_tag ON media.media_tags(tag_id);
CREATE INDEX media_categories_category ON media.media_categories(category_id);

-- Folder scopes a label may live on; the top-level ones are made automatically.
CREATE TABLE media.scopes (
  path       text PRIMARY KEY,
  automatic  integer NOT NULL DEFAULT 0 CHECK (automatic IN (0, 1)),
  created_at bigint NOT NULL,
  created_by text
);

CREATE TABLE media.sync_state (key text PRIMARY KEY, value text);

-- D17: who added what, copied from panel.db's media_notes when media.db was made.
CREATE TABLE media.imported_notes (
  path     text PRIMARY KEY,
  added_by text NOT NULL,
  added_at bigint NOT NULL,
  how      text NOT NULL CHECK (how IN ('uploaded', 'copied'))
);

-- D18: a thumbnail per record, made for one hash. The picture itself is a file,
-- <thumbs dir>/<id>-<hash>.webp; an icon stands in when there's no picture.
CREATE TABLE media.thumbs (
  media_id bigint PRIMARY KEY REFERENCES media.media(id) ON DELETE CASCADE,
  hash     text NOT NULL,                  -- the content it was made from
  result   text NOT NULL CHECK (result IN ('picture', 'icon')),
  icon     text,                           -- what stands in (always set: a picture can fail to load)
  width    bigint,
  height   bigint,
  why      text,                           -- why there's only an icon
  made_at  bigint NOT NULL
);

-- D7: a tag or category only links to files under its own scope, whichever side
-- changes. Same messages as the SQLite triggers. The port loads rows with these
-- off (SQLite already checked them) and then checks every link once.
CREATE FUNCTION media.check_label_link() RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  IF TG_TABLE_NAME = 'media_tags' THEN
    IF NOT EXISTS (SELECT 1 FROM media.tags l JOIN media.media m ON m.id = NEW.media_id
                    WHERE l.id = NEW.tag_id AND media.path_under(l.scope, m.path)) THEN
      RAISE EXCEPTION 'a tag only goes on files in its own scope' USING ERRCODE = 'check_violation';
    END IF;
  ELSE
    IF NOT EXISTS (SELECT 1 FROM media.categories l JOIN media.media m ON m.id = NEW.media_id
                    WHERE l.id = NEW.category_id AND media.path_under(l.scope, m.path)) THEN
      RAISE EXCEPTION 'a category only goes on files in its own scope' USING ERRCODE = 'check_violation';
    END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER media_tags_scope BEFORE INSERT OR UPDATE ON media.media_tags
  FOR EACH ROW EXECUTE FUNCTION media.check_label_link();
CREATE TRIGGER media_categories_scope BEFORE INSERT OR UPDATE ON media.media_categories
  FOR EACH ROW EXECUTE FUNCTION media.check_label_link();

CREATE FUNCTION media.check_label_scope() RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  IF (TG_TABLE_NAME = 'tags' AND EXISTS (
        SELECT 1 FROM media.media_tags x JOIN media.media m ON m.id = x.media_id
         WHERE x.tag_id = NEW.id AND NOT media.path_under(NEW.scope, m.path)))
  OR (TG_TABLE_NAME = 'categories' AND EXISTS (
        SELECT 1 FROM media.media_categories x JOIN media.media m ON m.id = x.media_id
         WHERE x.category_id = NEW.id AND NOT media.path_under(NEW.scope, m.path))) THEN
    RAISE EXCEPTION 'files in another scope still have this label' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NULL;
END $$;
CREATE TRIGGER tags_scope_change AFTER UPDATE OF scope ON media.tags
  FOR EACH ROW EXECUTE FUNCTION media.check_label_scope();
CREATE TRIGGER categories_scope_change AFTER UPDATE OF scope ON media.categories
  FOR EACH ROW EXECUTE FUNCTION media.check_label_scope();

CREATE FUNCTION media.check_media_scope() RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM media.media_tags x JOIN media.tags t ON t.id = x.tag_id
              WHERE x.media_id = NEW.id AND NOT media.path_under(t.scope, NEW.path))
  OR EXISTS (SELECT 1 FROM media.media_categories x JOIN media.categories c ON c.id = x.category_id
              WHERE x.media_id = NEW.id AND NOT media.path_under(c.scope, NEW.path)) THEN
    RAISE EXCEPTION 'move the labels to the new scope first' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NULL;
END $$;
CREATE TRIGGER media_scope_change AFTER UPDATE OF path, scope ON media.media
  FOR EACH ROW EXECUTE FUNCTION media.check_media_scope();
