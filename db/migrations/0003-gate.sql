-- The gate's protected folders, visitors, forms and API keys: gate.db as it
-- stands at user_version 10 (docs/postgres-plan.md P6). INTEGER -> bigint, 0/1
-- flags stay integer, JSON stays text.
--
-- The tables that were AUTOINCREMENT in SQLite (areas, visitors, forms, api_keys)
-- promise an id is never reused. A Postgres sequence never goes back, and the port
-- starts each one past sqlite_sequence, not just past max(id) (P7).
--
-- Appended, never edited: tools/migrate.ts refuses a file whose checksum changed.

-- Protected folders. A stray marker left by a deleted area can never unlock
-- anything: ids and tokens are never reused.
CREATE TABLE gate.areas (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token         text NOT NULL UNIQUE,
  path          text NOT NULL UNIQUE,
  created_at    bigint NOT NULL,
  requests_open integer NOT NULL DEFAULT 1
);

-- password_hash is '' until they choose one with a setup link
CREATE TABLE gate.visitors (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username            text NOT NULL UNIQUE,
  name                text NOT NULL DEFAULT '',
  password_hash       text NOT NULL,
  active              integer NOT NULL DEFAULT 1,
  created_at          bigint NOT NULL,
  password_changed_at bigint NOT NULL,
  contact             text NOT NULL DEFAULT ''
);

CREATE TABLE gate.grants (
  visitor_id bigint NOT NULL REFERENCES gate.visitors(id) ON DELETE CASCADE,
  area_id    bigint NOT NULL REFERENCES gate.areas(id) ON DELETE CASCADE,
  created_at bigint NOT NULL,
  PRIMARY KEY (visitor_id, area_id)
);

CREATE TABLE gate.sessions (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token_hash   text NOT NULL UNIQUE,
  visitor_id   bigint NOT NULL REFERENCES gate.visitors(id) ON DELETE CASCADE,
  host         text NOT NULL,
  created_at   bigint NOT NULL,
  last_seen_at bigint NOT NULL,
  expires_at   bigint NOT NULL,
  revoked_at   bigint,
  ip           text
);
CREATE INDEX sessions_visitor ON gate.sessions(visitor_id);

CREATE TABLE gate.events (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at         bigint NOT NULL,
  visitor_id bigint REFERENCES gate.visitors(id) ON DELETE SET NULL,
  username   text,
  area_id    bigint,
  event      text NOT NULL,
  host       text,
  ip         text
);
CREATE INDEX events_at ON gate.events(at);

-- One-time links to choose a password: a new person's first, or a new one after
-- they forgot it. Only the token's SHA-256 is kept.
CREATE TABLE gate.links (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token_hash   text NOT NULL UNIQUE,
  visitor_id   bigint NOT NULL REFERENCES gate.visitors(id) ON DELETE CASCADE,
  area_id      bigint REFERENCES gate.areas(id) ON DELETE SET NULL,
  created_at   bigint NOT NULL,
  expires_at   bigint NOT NULL,
  used_at      bigint,
  cancelled_at bigint
);
CREATE INDEX links_visitor ON gate.links(visitor_id);

-- access: someone asking to open a folder. reset: someone who forgot their password.
CREATE TABLE gate.requests (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind       text NOT NULL CHECK (kind IN ('access', 'reset')),
  area_id    bigint REFERENCES gate.areas(id) ON DELETE SET NULL,
  visitor_id bigint REFERENCES gate.visitors(id) ON DELETE SET NULL,
  name       text NOT NULL DEFAULT '',
  contact    text NOT NULL DEFAULT '',
  message    text NOT NULL DEFAULT '',
  host       text,
  ip         text,
  created_at bigint NOT NULL,
  status     text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'done', 'declined')),
  handled_at bigint,
  handled_by text
);
CREATE INDEX requests_status ON gate.requests(status, created_at);

-- Forms (docs/forms-plan.md). The id is never reused: API addresses use it.
CREATE TABLE gate.forms (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name            text NOT NULL UNIQUE,          -- olivias-form; can't change; taken while in the trash
  title           text NOT NULL,
  items           text NOT NULL,                 -- JSON: forms.ts Item[]
  settings        text NOT NULL,                 -- JSON: forms.ts Settings
  used_keys       text NOT NULL DEFAULT '[]',    -- JSON: every field key it has had
  enabled         integer NOT NULL DEFAULT 1,
  approvable      integer NOT NULL DEFAULT 0,
  public_approved integer NOT NULL DEFAULT 0,
  version         bigint NOT NULL DEFAULT 1,
  created_at      bigint NOT NULL,
  created_by      text,
  updated_at      bigint NOT NULL,
  updated_by      text,
  trashed_at      bigint,
  trashed_by      text,
  fixture         text,                          -- the worked example it is (guestbook, rsvp, pinboard), else NULL
  auto_approve    integer NOT NULL DEFAULT 0,    -- "Show right away" (docs/auto-approve-plan.md)
  scope           text NOT NULL DEFAULT '/'      -- '/' every page of her site, '/olivia' only inside olivia/
);
CREATE UNIQUE INDEX forms_fixture ON gate.forms(fixture) WHERE fixture IS NOT NULL;

-- Each response keeps the form's name and each field's key and label as they
-- were when it was sent, so editing or deleting the form never changes it.
CREATE TABLE gate.responses (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  form_id          bigint REFERENCES gate.forms(id) ON DELETE SET NULL,
  form_name        text NOT NULL,
  page             text NOT NULL,
  answers          text NOT NULL,       -- JSON: [{key, label, type, value}]
  visitor_id       bigint REFERENCES gate.visitors(id) ON DELETE SET NULL,
  visitor_username text,                -- who sent it, on a page in a protected folder
  visitor_name     text,
  host             text,
  ip               text,
  created_at       bigint NOT NULL,
  read_at          bigint,
  read_by          text,
  trashed_at       bigint,
  trashed_by       text,
  approved_at      bigint,
  approved_by      text,
  approved_auto    integer NOT NULL DEFAULT 0   -- approved by "Show right away", not by hand
);
CREATE INDEX responses_created ON gate.responses(created_at);
CREATE INDEX responses_form ON gate.responses(form_id, created_at, id);
CREATE INDEX responses_approved ON gate.responses(form_id, approved_at);

-- For the API's filterby: one row per answer (per choice, per name/address part).
CREATE TABLE gate.response_values (
  response_id bigint NOT NULL REFERENCES gate.responses(id) ON DELETE CASCADE,
  form_id     bigint,
  key         text NOT NULL,
  value       text NOT NULL
);
CREATE INDEX response_values_response ON gate.response_values(response_id, key);
CREATE INDEX response_values_find ON gate.response_values(form_id, key, value);

-- Pages a form was shown on lately ("Used on"), noted at most once an hour per page.
CREATE TABLE gate.form_pages (
  form_id   bigint NOT NULL REFERENCES gate.forms(id) ON DELETE CASCADE,
  page      text NOT NULL,
  last_seen bigint NOT NULL,
  PRIMARY KEY (form_id, page)
);

CREATE TABLE gate.api_keys (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  label        text NOT NULL,
  prefix       text NOT NULL,                  -- the first 14 characters, to tell keys apart
  key_hash     text NOT NULL UNIQUE,           -- SHA-256 of the key; the key itself is never kept
  level        text NOT NULL CHECK (level IN ('approved', 'all')),
  forms        text NOT NULL,                  -- JSON: null (every form) or [form ids]
  created_at   bigint NOT NULL,
  created_by   text,
  last_used_at bigint,
  revoked_at   bigint,
  revoked_by   text,
  media        text NOT NULL DEFAULT 'null'    -- JSON: null (none), "all", or scopes like ["/olivia"]
);
