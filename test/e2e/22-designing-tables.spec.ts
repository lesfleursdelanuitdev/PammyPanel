// Designing a table in a browser (docs/databases-plan.md 6, 8 and 10). The
// engines are stood in for by test/e2e/server.ts, so what is real here is the
// part she touches: that nothing changes until Apply, that Review says what each
// change costs, and that the SQL under Advanced is there to look at.
import { confirmDialog, expect, notice, test } from './fixtures.ts';

const tables = (page: import('@playwright/test').Page) => page.getByRole('list', { name: 'Tables' });
const fields = (page: import('@playwright/test').Page) => page.getByRole('list', { name: 'Fields' });

// family_recipes is on her Postgres with one table in it already (server.ts).
// The panel has to be looking after a database before it can design it -- and
// the tests in this file take turns, so only the first one has to pick it up.
const open = async (page: import('@playwright/test').Page) => {
  await page.goto('/databases');
  // The cards arrive from the engines, so the page is still <Loading /> for a
  // moment after goto() resolves. Wait for the list to be drawn before looking
  // for the button: count() is the one locator call that does NOT wait, so
  // counting too early silently finds nothing and skips picking the database up.
  await expect(page.getByRole('list', { name: 'Your databases' })).toBeVisible();
  const adopt = page.getByRole('listitem').filter({ hasText: 'family_recipes' })
    .getByRole('button', { name: 'Look after this one' });
  if (await adopt.count()) {
    await adopt.first().click();
    await expect(notice(page)).toContainText('looking after family_recipes');
  }
  await page.goto('/databases/postgres/family_recipes');
};

test('draw a table, review what it would do, and apply it', async ({ page }) => {
  await open(page);
  await expect(page.getByRole('heading', { name: 'family_recipes', level: 1 })).toBeVisible();
  // what is already in it, read from the engine
  await expect(tables(page)).toContainText('recipes');
  await expect(tables(page)).toContainText('4 fields');

  await page.getByRole('button', { name: 'Add table' }).click();
  const ask = page.getByRole('alertdialog');
  await ask.getByRole('textbox').fill('guests');
  await ask.getByRole('button', { name: 'Add it' }).click();
  await expect(notice(page)).toContainText('Nothing has changed in the database yet.');

  // a new table is not an empty rectangle: it comes with the key and the dates
  const guests = tables(page).getByRole('listitem').filter({ hasText: 'guests' });
  await expect(guests).toContainText('not made yet');
  await expect(guests).toContainText('id');
  await expect(guests).toContainText('created_at');

  await expect(page.getByText('Not applied yet')).toBeVisible();
  await page.getByRole('link', { name: 'Review changes' }).click();

  await expect(page.getByRole('heading', { name: 'Review changes', level: 1 })).toBeVisible();
  await expect(page.getByRole('list', { name: 'Changes' })).toContainText('New table guests, with 3 fields');
  // this one is Postgres, so it says so before she presses anything
  await expect(page.getByText('These are applied all together')).toBeVisible();

  // and what it will really run is there to look at
  await page.getByText('Advanced: what the database will be asked to do').click();
  await expect(page.locator('pre')).toContainText('CREATE TABLE "guests"');
  await expect(page.locator('pre')).toContainText('GENERATED BY DEFAULT AS IDENTITY');

  await page.getByRole('button', { name: 'Apply 1 change' }).click();
  await confirmDialog(page).getByRole('button', { name: 'Apply them' }).click();
  await expect(notice(page)).toContainText('1 change applied to family_recipes.');
  // back on the tables, with nothing waiting and the table really there
  await expect(page.getByText('Not applied yet')).toBeHidden();
  await expect(tables(page).getByRole('listitem').filter({ hasText: 'guests' })).not.toContainText('not made yet');
});

test('a field she cannot change says so instead of offering her nothing', async ({ page }) => {
  await open(page);
  await tables(page).getByRole('listitem').filter({ hasText: 'recipes' }).getByRole('link', { name: 'Fields' }).click();
  await expect(page.getByRole('heading', { name: 'recipes', level: 1 })).toBeVisible();

  // `tags` is a text[] in the stub: a kind the panel does not offer
  const tags = fields(page).getByRole('listitem').filter({ hasText: 'tags' });
  await expect(tags).toContainText('left as it is');
  await expect(tags).toContainText('does not offer');
  await expect(tags.getByLabel('What goes in it')).toBeHidden();

  // the key is settled when the table is made
  const id = fields(page).getByRole('listitem').filter({ hasText: 'id' }).first();
  await expect(id).toContainText('primary key');
  await expect(id).toContainText('settled when the table is made');
  await expect(id.getByRole('button', { name: 'Remove' })).toBeHidden();
});

test('removing a field says what it costs, and says it again on Review', async ({ page }) => {
  await open(page);
  await tables(page).getByRole('listitem').filter({ hasText: 'recipes' }).getByRole('link', { name: 'Fields' }).click();

  const servings = fields(page).getByRole('listitem').filter({ hasText: 'servings' });
  await expect(servings).toContainText('starts out as 4');
  await servings.getByRole('button', { name: 'Remove' }).click();
  await expect(page.getByRole('alertdialog')).toContainText('is deleted');
  await page.getByRole('alertdialog').getByRole('button', { name: 'Add it to the changes' }).click();
  await expect(notice(page)).toContainText('on the list of changes');

  await page.goto('/databases/postgres/family_recipes/review');
  const change = page.getByRole('list', { name: 'Changes' }).getByRole('listitem').first();
  await expect(change).toContainText('Remove recipes.servings');
  await expect(change).toContainText('deletes something');
  await expect(change).toContainText('cannot be undone here');
  await expect(page.getByText('You will be asked for your passkey')).toBeVisible();

  // and she can change her mind: the database is untouched either way
  await page.getByRole('button', { name: 'Throw them away' }).click();
  await confirmDialog(page).getByRole('button', { name: 'Throw them away' }).click();
  await expect(notice(page)).toContainText('Back to what the database really has.');
  await page.goto('/databases/postgres/family_recipes/tables/recipes');
  await expect(fields(page)).toContainText('servings');
});

test('renaming a field is a rename, not a field thrown away', async ({ page }) => {
  await open(page);
  await page.goto('/databases/postgres/family_recipes/tables/recipes');

  const title = fields(page).getByRole('listitem').filter({ hasText: 'title' });
  await title.getByRole('button', { name: 'Rename' }).click();
  const ask = page.getByRole('alertdialog');
  await ask.getByRole('textbox').fill('headline');
  await ask.getByRole('button', { name: 'Rename it' }).click();
  await expect(notice(page)).toContainText('It is called headline in your drawing.');
  await expect(fields(page).getByRole('listitem').filter({ hasText: 'headline' })).toContainText('was title');

  await page.goto('/databases/postgres/family_recipes/review');
  const changes = page.getByRole('list', { name: 'Changes' });
  await expect(changes.getByRole('listitem')).toHaveCount(1);
  await expect(changes).toContainText('Rename recipes.title to headline');
  await expect(changes).not.toContainText('Remove');
  await expect(changes).toContainText('will stop working until it is changed too');

  // and put it back, so the next run of this file starts where this one did
  await page.getByRole('button', { name: 'Throw them away' }).click();
  await confirmDialog(page).getByRole('button', { name: 'Throw them away' }).click();
  await expect(notice(page)).toContainText('Back to what the database really has.');
});
