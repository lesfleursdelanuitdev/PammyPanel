// Writes the coupling report (docs/master-plan.md K0) from the code:
//
//   node tools/coupling/report.ts            docs/coupling-report.json and .md, anew
//   node tools/coupling/report.ts --check    exit 1 when the committed ones are out of date
//   node tools/coupling/report.ts --summary  the numbers, and every op call, on stdout
//
// test/coupling.test.ts runs --check's comparison in the fast tier, so a commit that adds or
// removes coupling carries the report that says so. The JSON is C1's allow list.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { makeReport, type Report } from './scan.ts';

const ROOT = join(import.meta.dirname, '..', '..');
export const JSON_FILE = 'docs/coupling-report.json';
export const MD_FILE = 'docs/coupling-report.md';

// What is committed: only what changes when coupling does. Counts of a module's own queries
// and the list of every op call change with any feature, so they stay out (--summary).
export function committed(r: Report) {
  const sites = new Map<string, Set<string>>();
  for (const n of r.naming) if (n.file.startsWith('sites/')) {
    const s = n.file.split('/')[1]!;
    if (!sites.has(s)) sites.set(s, new Set());
    sites.get(s)!.add(n.module);
  }
  return {
    about: 'Generated by tools/coupling/report.ts from the code (docs/master-plan.md K0). Do not edit: run the tool.',
    tables: r.tables,
    sql: r.sqlCross,
    sqlUnsure: r.sqlUnsure,
    undeclared: r.undeclared,
    gateOpsElsewhere: Object.fromEntries(Object.entries(r.gateOps).filter(([, o]) => o.runs.join() !== o.module)),
    unplacedOps: r.unplaced,
    kernelNames: r.naming.filter((n) => !n.file.startsWith('sites/')),
    sitesName: Object.fromEntries([...sites].sort(([a], [b]) => a.localeCompare(b)).map(([s, m]) => [s, [...m].sort()])),
  };
}

const list = (xs: string[]) => xs.map((x) => `\`${x}\``).join(', ');

export function markdown(r: Report): string {
  const c = committed(r);
  const L: string[] = [];
  const crossModules = new Set(c.sql.map((t) => t.module));
  const sitesSql = c.sql.filter((t) => t.module.startsWith('site:'));
  const kernelSql = c.sql.filter((t) => t.module === 'core' || t.module === 'gate');
  const modSql = c.sql.filter((t) => !t.module.startsWith('site:') && t.module !== 'core' && t.module !== 'gate');
  const coreOps = Object.entries(r.gateOps).filter(([, o]) => o.runs.includes('core')).map(([op]) => op);
  L.push('# Coupling report', '',
    '*Generated by `node tools/coupling/report.ts` from the code; do not edit. `test/coupling.test.ts`',
    'fails when it is out of date. The JSON beside it (`coupling-report.json`) is C1\'s allow list.*', '',
    'What each section checks is a rule in docs/master-plan.md section 3. Files, not lines: an',
    'edit doesn\'t change this report, only new or removed coupling does.', '');

  L.push('## Summary', '',
    '| What | How many |', '|---|---|',
    `| tables (and views), with an owner | ${Object.keys(c.tables).length} |`,
    `| SQL on another module's tables (module, table, read/write) | ${c.sql.length}, from ${crossModules.size} modules and sites |`,
    `| ... of them by the kernel or the gate host | ${kernelSql.length} |`,
    `| ... of them by the sites (rule 4: sites have no SQL) | ${sitesSql.length} |`,
    `| runtime dependencies not declared (rule 5) | ${c.undeclared.length} |`,
    `| gate ops whose code is another module's than the one they're switched with | ${Object.keys(c.gateOpsElsewhere).length} |`,
    `| gate ops answered by core's stores (K-a moves them) | ${coreOps.length} |`,
    `| places the kernel or gate host names a module (rule 3) | ${c.kernelNames.length} |`,
    `| SQL or ops the report couldn't place | ${c.sqlUnsure.length + c.unplacedOps.length} |`, '');

  L.push('## 1. Tables and their owners (rule 1)', '',
    'Owner: the package whose migration makes the table; for the closed baseline (`db/migrations`)',
    'the module it belongs to by meaning; a decided move overrides both (why).', '',
    '| Table | Owner | Made by | Why |', '|---|---|---|---|');
  for (const [t, i] of Object.entries(c.tables)) L.push(`| \`${t}\` | ${i.owner} | ${i.createdBy} | ${i.why ?? ''} |`);
  L.push('');

  const sqlTable = (rows: typeof c.sql) => {
    L.push('| Module | Table (owner) | Reads / writes | Files |', '|---|---|---|---|');
    for (const t of rows) L.push(`| ${t.module} | \`${t.table}\` (${c.tables[t.table]!.owner}) | ${t.access} | ${t.files.join('<br>')} |`);
    L.push('');
  };
  L.push('## 2. SQL on another module\'s tables', '', `### Modules (${modSql.length})`, '');
  sqlTable(modSql);
  L.push(`### The kernel and the gate host (${kernelSql.length})`, '');
  sqlTable(kernelSql);
  L.push(`### The sites (${sitesSql.length}; rule 4)`, '');
  sqlTable(sitesSql);

  L.push('## 3. Runtime dependencies through sockets (rule 5)', '',
    'A package sends an op to a server that answers for a module it doesn\'t list in its',
    '`package.json`. A gate op belongs to the module the gate\'s own `moduleOf()` gives it (the',
    'module that switches it on and off); a helper\'s ops to the helper\'s package. The sites may',
    'send anything and are left out.', '',
    '| Package | Needs, undeclared | Through |', '|---|---|---|');
  for (const u of c.undeclared) L.push(`| ${u.from} | ${u.to} | ${list(u.via)} |`);
  L.push('', '### Gate ops that run another module\'s code', '',
    'The op is switched with one module and runs another\'s code (`core`: the stores in',
    '`core/src/gate`, which K-a splits; `gate`: the gate\'s own).', '',
    '| Op | Switched with | Runs the code of |', '|---|---|---|');
  for (const [op, o] of Object.entries(c.gateOpsElsewhere)) L.push(`| \`${op}\` | ${o.module} | ${o.runs.join(', ')} |`);
  L.push('');

  L.push('## 4. Modules the kernel and the gate host name (rule 3)', '',
    '`import`: imports the module\'s package; `name`: a string that is exactly the module\'s name',
    '(a right, a profile entry, an `isOn()`).', '',
    '| File | Module | How | Times |', '|---|---|---|---|');
  for (const n of c.kernelNames) L.push(`| ${n.file} | ${n.module} | ${n.how} | ${n.count} |`);
  L.push('', '### What each site names', '',
    'Today a site imports and names the modules it puts together; C1 makes them compose from',
    'definitions instead.', '');
  for (const [s, m] of Object.entries(c.sitesName)) L.push(`- **${s}** (${m.length}): ${m.join(', ')}`);
  L.push('');

  L.push('## 5. What the report couldn\'t place', '');
  if (!c.sqlUnsure.length && !c.unplacedOps.length) L.push('Nothing.', '');
  for (const u of c.sqlUnsure) L.push(`- SQL: ${u.file} names \`${u.table}\`: ${u.why}`);
  for (const u of c.unplacedOps) L.push(`- op \`${u.op}\` in ${u.file}: ${u.why}`);
  L.push('');

  L.push('## 6. What it can\'t see', '',
    '- SQL a string doesn\'t hold whole: a table name put in with `${}` or `sql(name)`, a statement',
    '  built from pieces joined at run time, or comma joins (`FROM a, b`: only `a` is read).',
    '- SQL in `db/migrations` and `packages/*/migrations` (they make tables; the owner is who makes',
    '  them), in `test/`, `tools/` and `deploy/`, and in SQLite (the media index: `prepare` / `exec`',
    '  on a `DatabaseSync`).',
    '- Which process runs a file is read from its path (`src/gate/`, `packages/gate/`) and a short',
    '  list in `tools/coupling/scan.ts`; a file used by both sees the tables of the one its path says.',
    '- An op request built in one place and sent in another (section 5 lists them), and requests',
    '  through a client the tool doesn\'t know (it stops on a new JSON-line server).',
    '- A module named any other way than its exact name: a socket path, a URL, a nginx location,',
    '  a right called differently.',
    '- Coupling through files on disk (`gate-routes.json`, the media index, a helper\'s records).',
    '- Who a baseline table belongs to is by meaning (`BASELINE` in the tool), not found.', '');
  return L.join('\n');
}

if (import.meta.main) {
  const r = makeReport(ROOT);
  const json = `${JSON.stringify(committed(r), null, 2)}\n`;
  const md = markdown(r);
  if (process.argv.includes('--check')) {
    const stale = [[JSON_FILE, json], [MD_FILE, md]].filter(([f, want]) => {
      try { return readFileSync(join(ROOT, f!), 'utf8') !== want; } catch { return true; }
    }).map(([f]) => f);
    if (stale.length) { console.error(`out of date: ${stale.join(', ')}. Run: node tools/coupling/report.ts`); process.exit(1); }
    console.log('coupling report: up to date');
  } else if (process.argv.includes('--summary')) {
    console.log(`own-table queries ${r.sqlOwn}, other modules' tables ${r.sqlCross.length}, op calls ${r.calls.length}, undeclared ${r.undeclared.length}`);
    for (const x of r.calls) console.log(`${x.from} -> ${x.server}:${x.op} (${x.owner})  ${x.files.join(' ')}`);
  } else {
    writeFileSync(join(ROOT, JSON_FILE), json);
    writeFileSync(join(ROOT, MD_FILE), md);
    console.log(`wrote ${JSON_FILE} and ${MD_FILE}`);
  }
}
