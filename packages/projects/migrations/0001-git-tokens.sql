-- Git tokens (docs/phase8b-plan.md 8b-7, D7-2): a panel person's passwords for git over HTTPS
-- (https://git.<domain>/<project>.git). Kept as the SHA-256 of the token (base64url), never the
-- token: it is shown once, when it is made. A person turned off stops theirs at once (the check
-- reads users.active); a person deleted takes theirs along.
--
-- Appended, never edited: tools/migrate.ts refuses a file whose checksum changed.
CREATE TABLE panel.git_tokens (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      bigint NOT NULL REFERENCES panel.users (id) ON DELETE CASCADE,
  label        text   NOT NULL CHECK (length(label) BETWEEN 1 AND 60),
  hash         text   NOT NULL UNIQUE CHECK (hash ~ '^[A-Za-z0-9_-]{43}$'),
  -- the first characters after lfdln_git_, so a person can tell their tokens apart
  hint         text   NOT NULL CHECK (hint ~ '^[A-Za-z0-9_-]{4}$'),
  created_at   bigint NOT NULL,
  expires_at   bigint,            -- NULL: never
  last_used_at bigint
);
CREATE INDEX git_tokens_user ON panel.git_tokens (user_id);
