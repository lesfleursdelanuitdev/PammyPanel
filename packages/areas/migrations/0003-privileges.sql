-- Privileges (docs/roles-plan.md step 3): what a role set's app declares --
-- resources and their actions, its own verbs, groups of privileges, roles made
-- of groups plus single privileges, pairs never given together -- and
-- gate.grants gone (read-only and unread since step 2).
--
-- A privilege is still a text key (resource.action[:own|:any], role_privileges):
-- which keys a set may use is checked where they are written (the manifest
-- reader, the Access page), against its resources. pages.read is built in on
-- every set and never declared.
--
-- Appended, never edited: tools/migrate.ts refuses a file whose checksum changed.

DROP TABLE gate.grants;

-- the last pammy-panel.json that passed its checks, for a set made from one (R10)
ALTER TABLE gate.role_sets
  ADD COLUMN manifest text,
  ADD COLUMN manifest_read_at bigint,
  ADD CONSTRAINT role_sets_manifest_read CHECK ((manifest IS NULL) = (manifest_read_at IS NULL));

CREATE TABLE gate.resources (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_set_id bigint NOT NULL REFERENCES gate.role_sets(id) ON DELETE CASCADE,
  key         text NOT NULL CHECK (key ~ '^[a-z][a-z0-9-]{0,31}$' AND key <> 'pages'),
  label       text NOT NULL CHECK (length(label) BETWEEN 1 AND 80),
  owned       boolean NOT NULL DEFAULT false,   -- its privileges carry :own or :any (R7)
  UNIQUE (role_set_id, key)
);

CREATE TABLE gate.resource_actions (
  resource_id bigint NOT NULL REFERENCES gate.resources(id) ON DELETE CASCADE,
  action      text NOT NULL CHECK (action ~ '^[a-z][a-z0-9-]{0,31}$'),
  PRIMARY KEY (resource_id, action)
);

-- the app's own verbs beyond read/create/update/delete, with their words (R6)
CREATE TABLE gate.actions (
  role_set_id bigint NOT NULL REFERENCES gate.role_sets(id) ON DELETE CASCADE,
  key         text NOT NULL CHECK (key ~ '^[a-z][a-z0-9-]{0,31}$' AND key NOT IN ('read', 'create', 'update', 'delete')),
  label       text NOT NULL CHECK (length(label) BETWEEN 1 AND 80),
  PRIMARY KEY (role_set_id, key)
);

-- plain-language bundles of privileges (R8)
CREATE TABLE gate.groups (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_set_id bigint NOT NULL REFERENCES gate.role_sets(id) ON DELETE CASCADE,
  key         text NOT NULL CHECK (key ~ '^[a-z][a-z0-9-]{0,63}$'),
  label       text NOT NULL CHECK (length(label) BETWEEN 1 AND 80),
  UNIQUE (role_set_id, key),
  UNIQUE (id, role_set_id)
);

CREATE TABLE gate.group_privileges (
  group_id  bigint NOT NULL REFERENCES gate.groups(id) ON DELETE CASCADE,
  privilege text NOT NULL CHECK (privilege ~ '^[a-z][a-z0-9-]{0,31}\.[a-z][a-z0-9-]{0,31}(:(own|any))?$'),
  PRIMARY KEY (group_id, privilege)
);

-- a role's groups, from its own set; its privileges are theirs plus its own
-- role_privileges (the "extra privileges")
CREATE TABLE gate.role_groups (
  role_id     bigint NOT NULL,
  group_id    bigint NOT NULL,
  role_set_id bigint NOT NULL,
  PRIMARY KEY (role_id, group_id),
  FOREIGN KEY (role_id, role_set_id) REFERENCES gate.roles(id, role_set_id) ON DELETE CASCADE,
  FOREIGN KEY (group_id, role_set_id) REFERENCES gate.groups(id, role_set_id) ON DELETE CASCADE
);

-- roles that can never be combined (R11): the manifest's, and later the owner's
CREATE TABLE gate.never_together (
  role_set_id   bigint NOT NULL,
  role_a        bigint NOT NULL,
  role_b        bigint NOT NULL,
  from_manifest boolean NOT NULL DEFAULT false,
  PRIMARY KEY (role_a, role_b),
  CHECK (role_a < role_b),
  FOREIGN KEY (role_a, role_set_id) REFERENCES gate.roles(id, role_set_id) ON DELETE CASCADE,
  FOREIGN KEY (role_b, role_set_id) REFERENCES gate.roles(id, role_set_id) ON DELETE CASCADE
);

-- every privilege a role has: its own and its groups' (what the gate and the
-- panel's lists read)
CREATE VIEW gate.role_all_privileges AS
  SELECT role_id, privilege FROM gate.role_privileges
  UNION
  SELECT rg.role_id, gp.privilege FROM gate.role_groups rg JOIN gate.group_privileges gp ON gp.group_id = rg.group_id;
