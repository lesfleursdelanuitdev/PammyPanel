-- Roles under the hood (docs/roles-plan.md step 2): who may open what is now a
-- role in the area's role set, not a yes/no grant. Same answers everywhere:
-- every grant becomes Member of the built-in "Protected folder" set, whose one
-- role opens the folder's pages and whose two slots are empty.
--
-- Appended, never edited: tools/migrate.ts refuses a file whose checksum changed.

-- A set of roles an area uses. Built-in ones have a key and are never changed in
-- place (R4); a copy belongs to its area (step 4).
CREATE TABLE gate.role_sets (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key        text UNIQUE CHECK (key IS NULL OR key ~ '^[a-z][a-z0-9-]{0,63}$'),
  label      text NOT NULL CHECK (length(label) BETWEEN 1 AND 80),
  built_in   boolean NOT NULL DEFAULT false,
  created_at bigint NOT NULL,
  CHECK (built_in = (key IS NOT NULL))
);

-- The roles in a set. slot 'not-signed-in' is the fixed slot for people not
-- signed in: it holds privileges, and nobody is ever given it.
CREATE TABLE gate.roles (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_set_id bigint NOT NULL REFERENCES gate.role_sets(id) ON DELETE CASCADE,
  key         text NOT NULL CHECK (key ~ '^[a-z][a-z0-9-]{0,63}$'),
  label       text NOT NULL CHECK (length(label) BETWEEN 1 AND 80),
  slot        text CHECK (slot IN ('not-signed-in')),
  UNIQUE (role_set_id, key),
  UNIQUE (id, role_set_id)
);
CREATE UNIQUE INDEX roles_one_slot ON gate.roles (role_set_id, slot) WHERE slot IS NOT NULL;

-- The other fixed slot: the role anyone signed in holds when they've been given
-- none in the area (NULL: nothing). Never the not-signed-in slot itself.
ALTER TABLE gate.role_sets ADD COLUMN signed_in_role_id bigint;
ALTER TABLE gate.role_sets ADD CONSTRAINT role_sets_signed_in_role
  FOREIGN KEY (signed_in_role_id, id) REFERENCES gate.roles(id, role_set_id) ON DELETE SET NULL (signed_in_role_id);

-- resource.action, or resource.action:own|:any (R6, R7)
CREATE TABLE gate.role_privileges (
  role_id   bigint NOT NULL REFERENCES gate.roles(id) ON DELETE CASCADE,
  privilege text NOT NULL CHECK (privilege ~ '^[a-z][a-z0-9-]{0,31}\.[a-z][a-z0-9-]{0,31}(:(own|any))?$'),
  PRIMARY KEY (role_id, privilege)
);

-- The built-in set every protected folder uses.
INSERT INTO gate.role_sets (key, label, built_in, created_at)
  VALUES ('protected-folder', 'Protected folder', true, extract(epoch FROM now())::bigint);
INSERT INTO gate.roles (role_set_id, key, label, slot)
  SELECT id, 'not-signed-in', 'Not signed in', 'not-signed-in' FROM gate.role_sets WHERE key = 'protected-folder';
INSERT INTO gate.roles (role_set_id, key, label)
  SELECT id, 'member', 'Member' FROM gate.role_sets WHERE key = 'protected-folder';
INSERT INTO gate.role_privileges (role_id, privilege)
  SELECT r.id, 'pages.read' FROM gate.roles r JOIN gate.role_sets s ON s.id = r.role_set_id
  WHERE s.key = 'protected-folder' AND r.key = 'member';

-- A built-in set's id by its key: a new area's default.
CREATE FUNCTION gate.built_in_set(k text) RETURNS bigint LANGUAGE sql STABLE
  RETURN (SELECT id FROM gate.role_sets WHERE key = k);

-- Every area has one role set in use.
ALTER TABLE gate.areas ADD COLUMN role_set_id bigint REFERENCES gate.role_sets(id);
UPDATE gate.areas SET role_set_id = gate.built_in_set('protected-folder');
ALTER TABLE gate.areas
  ALTER COLUMN role_set_id SET DEFAULT gate.built_in_set('protected-folder'),
  ALTER COLUMN role_set_id SET NOT NULL,
  ADD CONSTRAINT areas_id_role_set UNIQUE (id, role_set_id);

-- One role per person per area (R2). The role must be one of the area's set's,
-- and never the not-signed-in slot (checked where it's written: a slot is a row
-- like any other).
CREATE TABLE gate.memberships (
  visitor_id  bigint NOT NULL REFERENCES gate.visitors(id) ON DELETE CASCADE,
  area_id     bigint NOT NULL,
  role_set_id bigint NOT NULL,
  role_id     bigint NOT NULL,
  created_at  bigint NOT NULL,
  PRIMARY KEY (visitor_id, area_id),
  FOREIGN KEY (area_id, role_set_id) REFERENCES gate.areas(id, role_set_id) ON DELETE CASCADE,
  FOREIGN KEY (role_id, role_set_id) REFERENCES gate.roles(id, role_set_id) ON DELETE CASCADE
);
CREATE INDEX memberships_area ON gate.memberships (area_id);

-- Every grant, as Member.
INSERT INTO gate.memberships (visitor_id, area_id, role_set_id, role_id, created_at)
  SELECT g.visitor_id, g.area_id, a.role_set_id, r.id, g.created_at
  FROM gate.grants g JOIN gate.areas a ON a.id = g.area_id
  JOIN gate.roles r ON r.role_set_id = a.role_set_id AND r.key = 'member';

-- gate.grants stays one release, read-only, then goes (step 3). Deleting a
-- visitor or an area still cascades to it: that runs as the table's owner.
