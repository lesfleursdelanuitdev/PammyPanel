-- every other scope a path names: media.scopes, and any a record or a label is in that
-- media.scopes lacks (the automatic ones are only made when asked for); shallowest first,
-- each under its nearest ancestor that is a scope
-- (as media.scopes has it; one it lacks is automatic when it is a top-level folder, as
-- ensureAutomaticScopes would have made it)
CREATE TEMP TABLE move_scopes ON COMMIT DROP AS
  SELECT p.path,
         coalesce(ms.automatic, CASE WHEN strpos(substr(p.path, 2), '/') = 0 THEN 1 ELSE 0 END) AS automatic,
         coalesce(ms.created_at, extract(epoch FROM now())::bigint) AS created_at, ms.created_by
    FROM (SELECT path FROM media.scopes UNION SELECT scope FROM media.media UNION SELECT scope FROM media.tags UNION SELECT scope FROM media.categories) p
    LEFT JOIN media.scopes ms ON ms.path = p.path
   WHERE p.path <> '/';
DO $$
DECLARE r record;
BEGIN
  FOR r IN SELECT * FROM move_scopes ORDER BY length(path) - length(replace(path, '/', '')), path LOOP
    INSERT INTO catalog.scopes (parent_id, source_id, path, label, automatic, created_at, created_by)
    SELECT (SELECT s.id FROM catalog.scopes s WHERE s.source_id = 1 AND catalog.path_under(s.path, substr(r.path, 2))
             ORDER BY length(s.path) DESC LIMIT 1),
           1, r.path, r.path, r.automatic = 1, r.created_at, r.created_by;
  END LOOP;
END $$;

