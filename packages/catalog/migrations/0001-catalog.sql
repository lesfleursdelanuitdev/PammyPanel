-- ------------------------------------------------------------------ the same, or nothing (S2-3)
-- Counts, and a checksum of every row as the pages and the media API see it: a file's path,
-- scope, name and every column, with its labels by kind, scope and name; each label with its
-- scope, name and public; each scope with its path. Any difference and the whole migration
-- rolls back.
DO $$
DECLARE
  was text; now_ text; what text;
BEGIN
  FOR what, was, now_ IN
    SELECT 'files', (SELECT count(*)::text FROM media.media), (SELECT count(*)::text FROM catalog.items)
    UNION ALL SELECT 'file columns', (SELECT count(*)::text FROM media.media), (SELECT count(*)::text FROM files.files)
    UNION ALL SELECT 'labels', (SELECT ((SELECT count(*) FROM media.tags) + (SELECT count(*) FROM media.categories))::text), (SELECT count(*)::text FROM catalog.labels)
    UNION ALL SELECT 'links', (SELECT ((SELECT count(*) FROM media.media_tags) + (SELECT count(*) FROM media.media_categories))::text), (SELECT count(*)::text FROM catalog.links)
    UNION ALL SELECT 'thumbnails', (SELECT count(*)::text FROM media.thumbs), (SELECT count(*)::text FROM thumbs.thumbs)
    UNION ALL SELECT 'imported notes', (SELECT count(*)::text FROM media.imported_notes), (SELECT count(*)::text FROM files.imported_notes)
    UNION ALL SELECT 'sync state', (SELECT count(*)::text FROM media.sync_state), (SELECT count(*)::text FROM catalog.sync_state)
    UNION ALL SELECT 'scopes', (SELECT count(*)::text FROM (SELECT path FROM media.scopes UNION SELECT scope FROM media.media UNION SELECT scope FROM media.tags UNION SELECT scope FROM media.categories UNION SELECT '/') s),
                               (SELECT count(*)::text FROM catalog.scopes WHERE source_id = 1)
    UNION ALL SELECT 'every file and its labels',
      (SELECT md5(coalesce(string_agg(r, E'\n' ORDER BY r), '')) FROM (
         SELECT concat_ws('|', m.id, m.path, m.scope, m.kind, m.name, m.size, m.hash, m.modified_at, m.added_at, m.added_by, m.how, m.state, m.state_at, m.trash_id, m.changed_at, m.title, m.alt,
                  (SELECT string_agg('t:' || t.scope || ':' || t.name, ',' ORDER BY t.scope, t.name) FROM media.media_tags x JOIN media.tags t ON t.id = x.tag_id WHERE x.media_id = m.id),
                  (SELECT string_agg('c:' || c.scope || ':' || c.name, ',' ORDER BY c.scope, c.name) FROM media.media_categories x JOIN media.categories c ON c.id = x.category_id WHERE x.media_id = m.id)) AS r
           FROM media.media m) a),
      (SELECT md5(coalesce(string_agg(r, E'\n' ORDER BY r), '')) FROM (
         SELECT concat_ws('|', i.id, i.key, s.path, i.kind, f.name, f.size, f.hash, f.modified_at, f.added_at, f.added_by, f.how, i.state, i.state_at, f.trash_id, i.changed_at, i.title, f.alt,
                  (SELECT string_agg('t:' || ls.path || ':' || l.name, ',' ORDER BY ls.path, l.name) FROM catalog.links x JOIN catalog.labels l ON l.id = x.label_id JOIN catalog.scopes ls ON ls.id = l.scope_id WHERE x.item_id = i.id AND l.kind = 'tag'),
                  (SELECT string_agg('c:' || ls.path || ':' || l.name, ',' ORDER BY ls.path, l.name) FROM catalog.links x JOIN catalog.labels l ON l.id = x.label_id JOIN catalog.scopes ls ON ls.id = l.scope_id WHERE x.item_id = i.id AND l.kind = 'category')) AS r
           FROM catalog.items i JOIN catalog.scopes s ON s.id = i.scope_id JOIN files.files f ON f.item_id = i.id) b)
    UNION ALL SELECT 'every label',
      (SELECT md5(coalesce(string_agg(r, E'\n' ORDER BY r), '')) FROM (
         SELECT concat_ws('|', 'tag', id, scope, name, public = 1, created_at, created_by) AS r FROM media.tags
         UNION ALL SELECT concat_ws('|', 'category', scope, name, public = 1, created_at, created_by) FROM media.categories) a),
      (SELECT md5(coalesce(string_agg(r, E'\n' ORDER BY r), '')) FROM (
         SELECT CASE l.kind WHEN 'tag' THEN concat_ws('|', 'tag', l.id, s.path, l.name, l.public, l.created_at, l.created_by)
                            ELSE concat_ws('|', 'category', s.path, l.name, l.public, l.created_at, l.created_by) END AS r
           FROM catalog.labels l JOIN catalog.scopes s ON s.id = l.scope_id) b)
    UNION ALL SELECT 'every thumbnail',
      (SELECT md5(coalesce(string_agg(concat_ws('|', media_id, hash, result, icon, width, height, why, made_at), E'\n' ORDER BY media_id), '')) FROM media.thumbs),
      (SELECT md5(coalesce(string_agg(concat_ws('|', item_id, hash, result, icon, width, height, why, made_at), E'\n' ORDER BY item_id), '')) FROM thumbs.thumbs)
    UNION ALL SELECT 'every scope and whether it is automatic',
      (SELECT md5(string_agg(concat_ws('|', path, automatic = 1, created_at, created_by), E'\n' ORDER BY path)) FROM media.scopes),
      (SELECT md5(string_agg(concat_ws('|', path, automatic, created_at, created_by), E'\n' ORDER BY path)) FROM catalog.scopes WHERE path IN (SELECT path FROM media.scopes))
  LOOP
    IF was IS DISTINCT FROM now_ THEN
      RAISE EXCEPTION 'the catalog move would change %: % before, % after -- nothing was moved', what, was, now_;
    END IF;
  END LOOP;
END $$;

