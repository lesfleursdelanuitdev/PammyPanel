-- The catalog (docs/catalog-plan.md step 2, S2-1 to S2-3): tags and categories on items in
-- scopes, instead of on files in schema `media`. One migration, one transaction: the new
-- schemas, everything in `media` moved across, counts and checksums compared, and `media`
-- left read-only (step 3 drops it). Every site gets it; a site without files (lfdln) just
-- has empty tables.
--
--   catalog.sources      what offers items (here: the website, a File Explorer root)
--   catalog.resources    a source's kinds of item (here: its files)
--   catalog.scopes       one tree: All, then Website ('/'), then today's folder scopes
--   catalog.items        one per file (its id is the media record's: thumbnails, the media
--                        API and open pages keep working), state and title
--   catalog.labels       tags and categories (tags keep their ids; categories get new ones)
--   catalog.links        a label on an item (who made it: unknown before this step)
--   files.files          a file's own columns (File Explorer's)
--   thumbs.thumbs        a thumbnail per item (Thumbnails')
--
-- Appended, never edited: tools/migrate.ts refuses a file whose checksum changed.

-- ------------------------------------------------------------------ the schemas
-- (the owner owns the database, so it may make them; deploy/pg/setup.sql says the same
-- for a re-run of the roles' rights)
CREATE SCHEMA IF NOT EXISTS catalog;
CREATE SCHEMA IF NOT EXISTS files;
CREATE SCHEMA IF NOT EXISTS thumbs;
REVOKE ALL ON SCHEMA catalog, files, thumbs FROM PUBLIC;
GRANT USAGE ON SCHEMA catalog, files, thumbs TO pammy_panel;
ALTER DEFAULT PRIVILEGES IN SCHEMA catalog, files, thumbs GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO pammy_panel;
ALTER DEFAULT PRIVILEGES IN SCHEMA catalog, files, thumbs GRANT USAGE, SELECT ON SEQUENCES TO pammy_panel;
ALTER DEFAULT PRIVILEGES IN SCHEMA catalog, files, thumbs GRANT EXECUTE ON FUNCTIONS TO pammy_panel;

-- ------------------------------------------------------------------ the tables
CREATE TABLE catalog.sources (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind       text NOT NULL CHECK (kind IN ('files')),         -- Studio tables and apps: steps 4 and 5
  ref        text NOT NULL CHECK (length(ref) BETWEEN 1 AND 200),
  label      text NOT NULL CHECK (length(label) BETWEEN 1 AND 200),
  created_at bigint NOT NULL,
  UNIQUE (kind, ref)
);

CREATE TABLE catalog.resources (
  id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id bigint NOT NULL REFERENCES catalog.sources (id) ON DELETE CASCADE,
  key       text NOT NULL CHECK (key ~ '^[a-z][a-z0-9-]{0,39}$'),
  label     text NOT NULL CHECK (length(label) BETWEEN 1 AND 200),
  UNIQUE (source_id, key)
);

-- All has no parent and no source; a source's scopes are under All. For a File Explorer
-- source a scope's path is a folder under its root ('/' is the root itself, today's '/').
CREATE TABLE catalog.scopes (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_id  bigint REFERENCES catalog.scopes (id),          -- (checked at the end of a statement: a subtree goes in one)
  source_id  bigint REFERENCES catalog.sources (id) ON DELETE CASCADE,
  path       text,
  label      text NOT NULL CHECK (length(label) BETWEEN 1 AND 400),
  automatic  boolean NOT NULL DEFAULT false,
  created_at bigint NOT NULL,
  created_by text,
  CHECK ((parent_id IS NULL) = (source_id IS NULL)),
  CHECK ((source_id IS NULL) = (path IS NULL)),
  CHECK (path IS NULL OR path = '/' OR (length(path) >= 2 AND left(path, 1) = '/' AND right(path, 1) <> '/' AND strpos(path, '//') = 0)),
  UNIQUE (source_id, path)
);
CREATE UNIQUE INDEX scopes_one_all ON catalog.scopes ((true)) WHERE parent_id IS NULL;
CREATE INDEX scopes_parent ON catalog.scopes (parent_id);

-- key: a file's path under its root. scope: its site scope, as media.scope was ('/' or
-- '/<top folder>'; a file in media/ at the top is '/').
CREATE TABLE catalog.items (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  resource_id bigint NOT NULL REFERENCES catalog.resources (id) ON DELETE CASCADE,
  key         text NOT NULL CHECK (length(key) BETWEEN 1 AND 4096),
  scope_id    bigint NOT NULL REFERENCES catalog.scopes (id) ON DELETE RESTRICT,
  kind        text NOT NULL CHECK (kind IN ('images', 'files', 'audio', 'video', 'pages', 'other')),
  title       text,
  state       text NOT NULL DEFAULT 'present' CHECK (state IN ('present', 'trashed', 'missing')),
  state_at    bigint,
  changed_at  bigint NOT NULL
);
-- only one item per key that's there; one that went missing can share its old key
CREATE UNIQUE INDEX items_present_key ON catalog.items (resource_id, key) WHERE state = 'present';
CREATE INDEX items_key ON catalog.items (resource_id, key);
CREATE INDEX items_scope ON catalog.items (scope_id, kind, state);

-- File Explorer's own columns for an item that is a file
CREATE TABLE files.files (
  item_id     bigint PRIMARY KEY REFERENCES catalog.items (id) ON DELETE CASCADE,
  name        text NOT NULL,
  size        bigint NOT NULL,
  hash        text,
  modified_at bigint NOT NULL,
  added_at    bigint NOT NULL,
  added_by    text,
  how         text NOT NULL CHECK (how IN ('uploaded', 'copied', 'found')),
  trash_id    text,
  alt         text
);
CREATE INDEX files_trash ON files.files (trash_id) WHERE trash_id IS NOT NULL;

-- D17: who added what before the records existed (media.imported_notes)
CREATE TABLE files.imported_notes (
  path     text PRIMARY KEY,
  added_by text NOT NULL,
  added_at bigint NOT NULL,
  how      text NOT NULL CHECK (how IN ('uploaded', 'copied'))
);

CREATE TABLE catalog.labels (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scope_id   bigint NOT NULL REFERENCES catalog.scopes (id) ON DELETE RESTRICT,
  kind       text NOT NULL CHECK (kind IN ('tag', 'category')),
  name       text NOT NULL CHECK (length(name) BETWEEN 1 AND 40 AND name !~ '[^a-z0-9-]'),
  public     boolean NOT NULL DEFAULT false,
  created_at bigint NOT NULL,
  created_by text,
  UNIQUE (scope_id, kind, name)
);

-- made_by: the panel user who put it on (none known for what was there before this step)
CREATE TABLE catalog.links (
  item_id  bigint NOT NULL REFERENCES catalog.items (id) ON DELETE CASCADE,
  label_id bigint NOT NULL REFERENCES catalog.labels (id) ON DELETE CASCADE,
  made_by  text,
  made_at  bigint,
  PRIMARY KEY (item_id, label_id)
);
CREATE INDEX links_label ON catalog.links (label_id);

CREATE TABLE catalog.sync_state (key text PRIMARY KEY, value text);

CREATE TABLE thumbs.thumbs (
  item_id bigint PRIMARY KEY REFERENCES catalog.items (id) ON DELETE CASCADE,
  hash    text NOT NULL,
  result  text NOT NULL CHECK (result IN ('picture', 'icon')),
  icon    text,
  width   bigint,
  height  bigint,
  why     text,
  made_at bigint NOT NULL
);

-- The website's files as one row each, the way media.media had them: what File Explorer, the
-- Media pages and the media API read (writes go to the tables). The website is source 1.
CREATE VIEW files.records AS
  SELECT i.id, i.key AS path, s.path AS scope, i.kind, f.name, f.size, f.hash, f.modified_at, f.added_at, f.added_by, f.how,
         i.state, i.state_at, f.trash_id, i.changed_at, i.title, f.alt
    FROM catalog.items i JOIN files.files f ON f.item_id = i.id JOIN catalog.scopes s ON s.id = i.scope_id
   WHERE i.resource_id = 1;
REVOKE INSERT, UPDATE, DELETE ON files.records FROM pammy_panel;

-- A website file's record is whole and agrees with itself (media.media's checks, D5): its
-- file columns are there, its site scope and name follow from its path, and it is trashed
-- exactly when it has a trash id. Across two tables, so checked at the end of the
-- transaction that made the change.
CREATE FUNCTION files.check_record() RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $$
DECLARE
  r record;
  want text;
  rid bigint;
BEGIN
  IF TG_TABLE_NAME = 'items' THEN rid := NEW.id; ELSE rid := NEW.item_id; END IF;
  SELECT i.key, i.state, s.path AS scope, f.item_id, f.name, f.trash_id INTO r
    FROM catalog.items i JOIN catalog.scopes s ON s.id = i.scope_id LEFT JOIN files.files f ON f.item_id = i.id
   WHERE i.id = rid AND i.resource_id = 1;
  IF NOT FOUND THEN RETURN NULL; END IF;       -- (not the website's file, or deleted since)
  IF r.item_id IS NULL THEN
    RAISE EXCEPTION 'a file''s record has no file columns: %', r.key USING ERRCODE = 'check_violation';
  END IF;
  want := CASE WHEN strpos(r.key, '/') = 0 OR left(r.key, 6) = 'media/' THEN '/' ELSE '/' || left(r.key, strpos(r.key, '/') - 1) END;
  IF r.scope <> want OR NOT (r.key = r.name OR right(r.key, length(r.name) + 1) = '/' || r.name) THEN
    RAISE EXCEPTION 'a file''s record disagrees with its path (check constraint): %', r.key USING ERRCODE = 'check_violation';
  END IF;
  IF (r.state = 'trashed') <> (r.trash_id IS NOT NULL) THEN
    RAISE EXCEPTION 'a trashed file needs its trash id, and only a trashed one has one (check constraint): %', r.key USING ERRCODE = 'check_violation';
  END IF;
  RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER items_record AFTER INSERT OR UPDATE ON catalog.items
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION files.check_record();
CREATE CONSTRAINT TRIGGER files_record AFTER INSERT OR UPDATE ON files.files
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION files.check_record();

-- ------------------------------------------------------------------ labels stay in their scope (D7)
-- A label only goes on items under its scope, whichever side changes (media's triggers, with
-- the same messages). For a File Explorer source: the scope's path covers the item's key.
CREATE FUNCTION catalog.path_under(scope_path text, key text) RETURNS boolean
  LANGUAGE sql IMMUTABLE PARALLEL SAFE
  RETURN scope_path = '/' OR key = substr(scope_path, 2) OR starts_with(key, substr(scope_path, 2) || '/');

-- whether a label in this scope may go on this item: the same source, and under its path;
-- a label in All goes anywhere (C5)
CREATE FUNCTION catalog.label_fits(label_scope bigint, item bigint) RETURNS boolean
  LANGUAGE sql STABLE SET search_path = '' RETURN (
    SELECT s.parent_id IS NULL OR (s.source_id = r.source_id AND catalog.path_under(s.path, i.key))
      FROM catalog.scopes s, catalog.items i JOIN catalog.resources r ON r.id = i.resource_id
     WHERE s.id = label_scope AND i.id = item);

CREATE FUNCTION catalog.check_link() RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  IF NOT catalog.label_fits((SELECT scope_id FROM catalog.labels WHERE id = NEW.label_id), NEW.item_id) THEN
    IF (SELECT kind FROM catalog.labels WHERE id = NEW.label_id) = 'tag' THEN
      RAISE EXCEPTION 'a tag only goes on files in its own scope' USING ERRCODE = 'check_violation';
    END IF;
    RAISE EXCEPTION 'a category only goes on files in its own scope' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER links_scope BEFORE INSERT OR UPDATE ON catalog.links
  FOR EACH ROW EXECUTE FUNCTION catalog.check_link();

CREATE FUNCTION catalog.check_label_scope() RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM catalog.links x WHERE x.label_id = NEW.id AND NOT catalog.label_fits(NEW.scope_id, x.item_id)) THEN
    RAISE EXCEPTION 'files in another scope still have this label' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NULL;
END $$;
CREATE TRIGGER labels_scope_change AFTER UPDATE OF scope_id ON catalog.labels
  FOR EACH ROW EXECUTE FUNCTION catalog.check_label_scope();

-- a scope's path rewritten (a folder moved): its labels' items must still be under it
CREATE FUNCTION catalog.check_scope_path() RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM catalog.labels l JOIN catalog.links x ON x.label_id = l.id
              WHERE l.scope_id = NEW.id AND NOT catalog.label_fits(NEW.id, x.item_id)) THEN
    RAISE EXCEPTION 'files in another scope still have this label' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER scopes_path_change AFTER UPDATE OF path ON catalog.scopes
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION catalog.check_scope_path();

CREATE FUNCTION catalog.check_item_key() RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM catalog.links x JOIN catalog.labels l ON l.id = x.label_id
              WHERE x.item_id = NEW.id AND NOT catalog.label_fits(l.scope_id, NEW.id)) THEN
    RAISE EXCEPTION 'move the labels to the new scope first' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NULL;
END $$;
CREATE TRIGGER items_key_change AFTER UPDATE OF key, resource_id ON catalog.items
  FOR EACH ROW EXECUTE FUNCTION catalog.check_item_key();

