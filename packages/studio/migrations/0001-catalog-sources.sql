-- docs/catalog-plan.md step 4: a Studio table as a catalog source.
--
-- studio_resources.catalog_source: the table's source while "Let me tag these" is on (NULL:
-- off). By the Studio's row id, so renaming the table keeps it; the row going (the table
-- dropped, the database no longer looked after) takes the source and its labels with it.
ALTER TABLE panel.studio_resources
  ADD COLUMN catalog_source bigint UNIQUE REFERENCES catalog.sources (id) ON DELETE SET NULL,
  -- the field whose value is the record's picture ('' = none): a site path shows that
  -- file's thumbnail (S4-8)
  ADD COLUMN picture_field text NOT NULL DEFAULT '';

CREATE FUNCTION panel.studio_resource_gone() RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  IF OLD.catalog_source IS NOT NULL THEN PERFORM catalog.drop_source(OLD.catalog_source); END IF;
  RETURN NULL;
END $$;
CREATE TRIGGER studio_resources_gone AFTER DELETE ON panel.studio_resources
  FOR EACH ROW EXECUTE FUNCTION panel.studio_resource_gone();

-- A record's own columns (C2: the source's, not the catalog's): its picture field's value.
CREATE TABLE panel.studio_catalog_records (
  item_id bigint PRIMARY KEY REFERENCES catalog.items (id) ON DELETE CASCADE,
  picture text CHECK (picture IS NULL OR length(picture) <= 2000)
);

-- S4-3: the gate's writes to a table that is switched on (the data API, a form into a
-- table). The gate adds a line; the panel takes them every minute through the gate's
-- socket (and they go as they are taken). `key` is the record's, when the gate knows it
-- (a delete), else NULL: "this table changed, read it again".
CREATE TABLE gate.record_touches (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  database_id bigint NOT NULL,
  table_name  text NOT NULL CHECK (table_name ~ '^[a-z][a-z0-9_]{0,62}$'),
  key         text CHECK (key IS NULL OR length(key) BETWEEN 1 AND 4096),
  what        text NOT NULL CHECK (what IN ('changed', 'deleted')),
  at          bigint NOT NULL
);
