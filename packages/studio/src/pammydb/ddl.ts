// The dialect printers: one patch step in, the statements that carry it out on
// one engine. This is the only place in the tree that writes DDL, and it writes
// it from a structured step -- never from a string the page composed
// (docs/databases-plan.md 14).
//
// Everything that reaches a statement is either an identifier through quote()
// (which re-checks it against NAME_RE) or a value from an alphabet narrow enough
// that escaping has nothing to do (src/pammydb/ir.ts DEFAULT_TEXT_RE). There is
// no third kind.
//
// Pure and synchronous on purpose: the golden tests compare strings for both
// engines from the same patch, and Review shows exactly what Apply will run,
// because it is this function that produces both.
import { PammyDbError, quote, type Engine } from './ident.ts';
import type { Column, ColumnDefault, Table } from './ir.ts';
import type { Step } from './patch.ts';

const q = (engine: Engine, name: string) => quote(engine, name);

// Two starting values are the same one when this matches. It is the IR's own
// shape, so it works for the kinds the printers refuse as well as the ones they
// print.
const defaultKey = (c: Column): string => {
  const d = c.default;
  if (!d || d.kind === 'none') return 'none';
  return d.kind === 'now' ? 'now' : `${d.kind}:${'value' in d ? String(d.value) : d.sql}`;
};
const list = (engine: Engine, names: string[]) => names.map((n) => q(engine, n)).join(', ');

// ------------------------------------------------------------------ types

// docs/databases-plan.md 6, the table of what she picks and what it becomes.
export function sqlType(engine: Engine, c: Column): string {
  if (c.type === 'other') {
    // A column the panel did not make and does not understand. It can be
    // dropped or renamed -- neither needs the type -- but it is never made or
    // changed, because that would mean guessing what the engine meant.
    throw new PammyDbError('invalid', `The panel does not know how to make a field like ${c.name}, so it leaves it as it is.`);
  }
  const pg = engine === 'postgres';
  switch (c.type) {
    case 'text': return 'TEXT';
    case 'short_text': return `VARCHAR(${c.length ?? 255})`;
    case 'integer': return pg ? 'INTEGER' : 'INT';
    case 'decimal': return `${pg ? 'NUMERIC' : 'DECIMAL'}(${c.precision ?? 12}, ${c.scale ?? 2})`;
    // MariaDB has no boolean of its own: TINYINT(1) is what every client reads
    // back as one, which is why introspect reads it back the same way.
    case 'boolean': return pg ? 'BOOLEAN' : 'TINYINT(1)';
    case 'date': return 'DATE';
    case 'time': return 'TIME';
    // UTC in and out: TIMESTAMPTZ keeps the zone, DATETIME(6) does not, so the
    // helper is what makes sure only UTC ever goes into MariaDB.
    case 'timestamptz': return pg ? 'TIMESTAMPTZ' : 'DATETIME(6)';
    case 'uuid': return pg ? 'UUID' : 'CHAR(36)';
  }
}

function defaultSql(engine: Engine, c: Column): string | null {
  const d: ColumnDefault | null | undefined = c.default;
  if (!d || d.kind === 'none') return null;
  if (d.kind === 'raw') {
    // Read back from the engine, never printed into one. On MariaDB a MODIFY
    // restates the whole field, so a field with one of these cannot be changed
    // at all -- src/pammydb/ir.ts canAlter says so, and the page greys it out
    // long before this throws.
    throw new PammyDbError('invalid',
      `${c.name} starts out as ${d.sql}, which the panel cannot write down. It leaves that field exactly as it is.`);
  }
  const pg = engine === 'postgres';
  switch (d.kind) {
    case 'now':
      if (c.type === 'date') return pg ? 'CURRENT_DATE' : '(CURRENT_DATE)';
      if (c.type === 'time') return pg ? 'CURRENT_TIME' : '(CURRENT_TIME)';
      return pg ? 'now()' : 'CURRENT_TIMESTAMP(6)';
    case 'text':
      // DEFAULT_TEXT_RE has already ruled out quotes and backslashes; this is
      // the belt to that pair of braces.
      return `'${d.value.replaceAll("'", "''")}'`;
    case 'number':
      if (!Number.isFinite(d.value)) throw new PammyDbError('invalid', 'That starting value is not a number.');
      return String(d.value);
    case 'boolean':
      return pg ? (d.value ? 'TRUE' : 'FALSE') : (d.value ? '1' : '0');
  }
}

// One column as it appears inside CREATE TABLE or ADD COLUMN.
export function columnSql(engine: Engine, c: Column): string {
  const parts = [q(engine, c.name), sqlType(engine, c)];
  if (c.identity) {
    // Postgres: the engine supplies a number when nothing is given, and she can
    // still write her own in (BY DEFAULT, not ALWAYS -- importing rows with
    // their ids is a thing she will want). MariaDB: AUTO_INCREMENT, which the
    // engine only allows on a key, which checkTable has already insisted on.
    parts.push(engine === 'postgres' ? 'GENERATED BY DEFAULT AS IDENTITY' : 'AUTO_INCREMENT');
  }
  if (c.required) parts.push('NOT NULL');
  const d = defaultSql(engine, c);
  if (d) parts.push(`DEFAULT ${d}`);
  return parts.join(' ');
}

function createTableSql(engine: Engine, t: Table): string {
  const lines = t.columns.map((c) => columnSql(engine, c));
  if (t.primaryKey.length) lines.push(`PRIMARY KEY (${list(engine, t.primaryKey)})`);
  for (const u of t.uniques) lines.push(`CONSTRAINT ${q(engine, u.name)} UNIQUE (${list(engine, u.columns)})`);
  const body = `CREATE TABLE ${q(engine, t.name)} (${lines.join(', ')})`;
  // InnoDB, always: it is the only MariaDB engine with foreign keys, and
  // relationships are the point of the whole workspace.
  return engine === 'postgres' ? body : `${body} ENGINE=InnoDB`;
}

// ------------------------------------------------------------------ steps

// One step, one or more statements, in the order they must run. Postgres needs
// three statements to change a field (type, required, starting value); MariaDB
// restates the whole field in one, which is why it has to be given back every
// part of it -- including AUTO_INCREMENT, or MODIFY would quietly take it off.
export function statements(engine: Engine, step: Step): string[] {
  const pg = engine === 'postgres';
  const table = () => q(engine, step.kind === 'create-table' ? step.table.name : step.table);
  switch (step.kind) {
    case 'create-table':
      return [createTableSql(engine, step.table)];

    case 'drop-table':
      return [`DROP TABLE ${table()}`];

    case 'rename-table':
      return [pg
        ? `ALTER TABLE ${table()} RENAME TO ${q(engine, step.to)}`
        : `RENAME TABLE ${table()} TO ${q(engine, step.to)}`];

    case 'add-column':
      return [`ALTER TABLE ${table()} ADD COLUMN ${columnSql(engine, step.column)}`];

    case 'drop-column':
      return [`ALTER TABLE ${table()} DROP COLUMN ${q(engine, step.column)}`];

    case 'rename-column':
      return [`ALTER TABLE ${table()} RENAME COLUMN ${q(engine, step.column)} TO ${q(engine, step.to)}`];

    case 'alter-column': {
      const c = step.column;
      if (!pg) return [`ALTER TABLE ${table()} MODIFY COLUMN ${columnSql(engine, c)}`];
      const col = q(engine, c.name);
      const out: string[] = [];
      const typeChanged = c.type !== step.from.type
        || (c.length ?? null) !== (step.from.length ?? null)
        || (c.precision ?? null) !== (step.from.precision ?? null)
        || (c.scale ?? null) !== (step.from.scale ?? null);
      if (typeChanged) {
        // USING is what lets "text that holds numbers" become a whole number.
        // Postgres refuses the ones that cannot work, and that refusal reaches
        // her as a sentence rather than as a half-applied patch.
        out.push(`ALTER TABLE ${table()} ALTER COLUMN ${col} TYPE ${sqlType(engine, c)} USING ${col}::${sqlType(engine, c)}`);
      }
      if (c.required !== step.from.required) {
        out.push(`ALTER TABLE ${table()} ALTER COLUMN ${col} ${c.required ? 'SET NOT NULL' : 'DROP NOT NULL'}`);
      }
      // Compared as the IR has them, not as SQL: a starting value the printer
      // refuses (a raw one) must read as "unchanged" rather than throwing.
      if (defaultKey(c) !== defaultKey(step.from)) {
        const now = defaultSql(engine, c);
        out.push(`ALTER TABLE ${table()} ALTER COLUMN ${col} ${now ? `SET DEFAULT ${now}` : 'DROP DEFAULT'}`);
      }
      return out;
    }

    case 'add-unique':
      return [`ALTER TABLE ${table()} ADD CONSTRAINT ${q(engine, step.unique.name)} UNIQUE (${list(engine, step.unique.columns)})`];

    case 'drop-unique':
      // Postgres keeps it as a constraint; MariaDB's is an index, and DROP
      // CONSTRAINT there only reaches CHECK constraints.
      return [pg
        ? `ALTER TABLE ${table()} DROP CONSTRAINT ${q(engine, step.unique)}`
        : `ALTER TABLE ${table()} DROP INDEX ${q(engine, step.unique)}`];

    case 'add-foreign-key': {
      const f = step.foreignKey;
      const onDelete = f.onDelete === 'cascade' ? 'CASCADE' : f.onDelete === 'set null' ? 'SET NULL' : 'RESTRICT';
      return [`ALTER TABLE ${table()} ADD CONSTRAINT ${q(engine, f.name)} FOREIGN KEY (${list(engine, f.columns)})`
        + ` REFERENCES ${q(engine, f.references.table)} (${list(engine, f.references.columns)}) ON DELETE ${onDelete}`];
    }

    case 'drop-foreign-key':
      return [pg
        ? `ALTER TABLE ${table()} DROP CONSTRAINT ${q(engine, step.foreignKey)}`
        : `ALTER TABLE ${table()} DROP FOREIGN KEY ${q(engine, step.foreignKey)}`];
  }
}

// The whole patch as it will run, for Review's Advanced section. The helper
// prints this and the panel shows it, so what she reads is what runs rather
// than a second rendering that could drift from the first.
export const patchSql = (engine: Engine, steps: Step[]): string[] =>
  steps.flatMap((s) => statements(engine, s));
