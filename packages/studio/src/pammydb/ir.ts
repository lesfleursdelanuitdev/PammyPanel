// A new table is not an empty rectangle: it comes with the key she would have
// had to invent, and the two dates the generated list wants
// (docs/databases-plan.md 6, C13 -- suggested, and she can take them off before
// Apply).
export function starterTable(name: string): Table {
  return {
    name,
    columns: [
      { name: 'id', type: 'integer', required: true, identity: true, default: null, sqlType: null },
      { name: 'created_at', type: 'timestamptz', required: true, default: { kind: 'now' }, sqlType: null },
      { name: 'updated_at', type: 'timestamptz', required: false, default: { kind: 'now' }, sqlType: null },
    ],
    primaryKey: ['id'],
    uniques: [],
    foreignKeys: [],
    indexes: [],
  };
}

// A field she has just added: text, optional, nothing in it yet.
export const starterColumn = (name: string): Column =>
  ({ name, type: 'text', required: false, default: null, sqlType: null });

// Her words for a starting value, for the field row and for Review.
export function defaultLabel(d: ColumnDefault | null | undefined): string | null {
  if (!d || d.kind === 'none') return null;
  switch (d.kind) {
    case 'now': return 'the moment it is added';
    case 'text': return d.value === '' ? 'empty text' : `"${d.value}"`;
    case 'number': return String(d.value);
    case 'boolean': return d.value ? 'yes' : 'no';
    case 'raw': return d.sql;
  }
}

export const typeLabel = (c: Column): string => {
  if (c.type === 'other') return c.sqlType ?? 'something else';
  if (c.type === 'short_text') return `${TYPE_NAMES.short_text} (${c.length ?? 255})`;
  if (c.type === 'decimal' && (c.precision ?? 12) !== 12) return `${TYPE_NAMES.decimal} (${c.precision}, ${c.scale})`;
  return TYPE_NAMES[c.type];
};

// Whether this column is one the panel is able to change. Two kinds are not:
// a type the panel did not make (it would have to guess what the engine meant)
// and a starting value it cannot write down (MariaDB's MODIFY restates the whole
// field, so altering one of those would take the default off). Guessing about a
// column with her data in it is the one thing the studio must never do.
export const canAlter = (c: Column): boolean => c.type !== 'other' && c.default?.kind !== 'raw';

// Why not, in her words, for the line under the field on the Tables page.
export function whyNotAlterable(c: Column): string | null {
  if (c.type === 'other') return `This field is a ${c.sqlType ?? 'kind'} the panel does not offer, so it leaves it exactly as it is.`;
  if (c.default?.kind === 'raw') return `This field starts out as ${c.default.sql}, which the panel cannot write down, so it leaves the field as it is.`;
  return null;
}

