// One model of a schema, engine-agnostic, shared by the designer, the diff, the
// dialect printers and (later) inference: docs/studio-plan.md, "the shared IR".
// Nothing here talks to a database and nothing here composes SQL -- it is all
// types and string rules, so the panel and the web app can import it as freely
// as they import ident.ts.
//
// Two things it is careful about:
//
//  * **It describes storage, not meaning.** "Is this a long text box or a
//    one-line input?" is a Resource question (docs/databases-plan.md 11) and is
//    not answerable from an engine, because both are TEXT. The IR says `text`
//    and the control arrives with Resources.
//  * **It can describe a column it would never have made.** An adopted database
//    is full of types the panel does not offer. Those read back as `other`,
//    carrying the engine's own words for them, and the panel shows them and
//    leaves them alone rather than pretending they are something it knows.
import { createHash } from 'node:crypto';
import { NAME_RE, PammyDbError, type Engine } from './ident.ts';

// The types she picks without opening Advanced (docs/databases-plan.md 6).
// `other` is not one of them: it is what introspect says about everything else.
export const COLUMN_TYPES = [
  'text', 'short_text', 'integer', 'decimal', 'boolean', 'date', 'time', 'timestamptz', 'uuid',
] as const;

export type ColumnType = (typeof COLUMN_TYPES)[number] | 'other';

// Her words for each, and a line saying what it is for. The panel and the web
// app both read this, so the type list on the page and the type list the helper
// will accept cannot drift apart.
export const TYPE_NAMES: Record<ColumnType, string> = {
  text: 'Text',
  short_text: 'Short text',
  integer: 'Whole number',
  decimal: 'Decimal number',
  boolean: 'Yes / no',
  date: 'Date',
  time: 'Time',
  timestamptz: 'Date and time',
  uuid: 'Unique id',
  other: 'Something else',
};

export const TYPE_HINTS: Record<ColumnType, string> = {
  text: 'Any amount of writing — a title, a paragraph, a whole page.',
  short_text: 'Writing with a length limit, like a postcode or a two-letter country.',
  integer: 'A number with nothing after the point: 0, 7, 2026.',
  decimal: 'A number with a point in it, like a price: 12.50.',
  boolean: 'A tick box: yes or no, on or off.',
  date: 'A day, with no time of day.',
  time: 'A time of day, with no date.',
  timestamptz: 'A moment: the day and the time, kept in UTC.',
  uuid: 'A long random id, the kind programs make for themselves.',
  other: 'Something this database already had that the panel does not offer. It is left exactly as it is.',
};

export const isColumnType = (v: unknown): v is ColumnType =>
  v === 'other' || (COLUMN_TYPES as readonly unknown[]).includes(v);

// What a column starts out as when nothing is stored in it yet.
//
// A default reaches SQL inside a DDL statement, where no engine will bind a
// placeholder, so the same rule as passwords applies: narrow the alphabet until
// escaping has nothing to do. `now` is the one expression allowed, because it is
// the one she actually wants (docs/databases-plan.md 6, created_at).
export type ColumnDefault =
  | { kind: 'none' }
  | { kind: 'now' }
  | { kind: 'text'; value: string }
  | { kind: 'number'; value: number }
  | { kind: 'boolean'; value: boolean }
  // What introspect found where the four above do not fit: a function call, a
  // sequence, an expression she wrote in her own client. It is carried so the
  // draft does not quietly forget it, shown as the engine's own words, and
  // never printed back into DDL -- which is why a field that has one cannot be
  // changed here at all (canAlter). The alternative was to restate it, and a
  // MariaDB MODIFY that restates a default the panel guessed at would be the
  // panel changing something she did not ask it to touch.
  | { kind: 'raw'; sql: string };

// No quotes, no backslashes (MariaDB reads one as an escape), nothing that ends
// a statement. Punctuation she would actually type in a default is fine.
export const DEFAULT_TEXT_RE = /^[A-Za-z0-9 .,_@:+/()?!%&#-]{0,100}$/;

export type Column = {
  name: string;
  // Draft only, exactly like Table.was: the name this field has on the engine.
  was?: string;
  type: ColumnType;
  // what the engine calls it. Introspect always fills this in; `other` is only
  // ever meaningful with it, and the panel shows it beside the name.
  sqlType?: string | null;
  length?: number | null;              // short_text
  precision?: number | null;           // decimal
  scale?: number | null;               // decimal
  required: boolean;                   // NOT NULL
  default?: ColumnDefault | null;
  // the engine fills it in: Postgres GENERATED BY DEFAULT AS IDENTITY, MariaDB
  // AUTO_INCREMENT. Only ever on a primary key, and only on a whole number.
  identity?: boolean;
};

export type ForeignKey = {
  name: string;
  columns: string[];
  references: { table: string; columns: string[] };
  onDelete: 'restrict' | 'cascade' | 'set null';
};

export type Unique = { name: string; columns: string[] };

// Read, shown, and never diffed in slice 4 (S15): an index the panel did not
// make rides along untouched rather than being proposed for deletion.
export type Index = { name: string; columns: string[]; unique: boolean };

export type Table = {
  name: string;
  // Draft only. What this table was called on the engine, when she has renamed
  // it and not applied yet -- it is how the diff tells a rename from a table
  // dropped and another one made, and it is why Review can say `title ->
  // headline` at all. Introspect never sets it; Apply clears it.
  was?: string;
  columns: Column[];
  primaryKey: string[];
  uniques: Unique[];
  foreignKeys: ForeignKey[];
  indexes: Index[];
};

export type Snapshot = {
  engine: Engine;
  database: string;
  tables: Table[];
  // Tables the studio role cannot see into are not silently missing: a snapshot
  // says so, and the page repeats it.
  notes: string[];
};

export const emptySnapshot = (engine: Engine, database: string): Snapshot =>
  ({ engine, database, tables: [], notes: [] });

// ------------------------------------------------------------------ reading one back

// A snapshot arrives from the helper as JSON and a draft arrives from a browser.
// Both go through here: the IR is the only thing either side may say, and a
// draft that does not parse is refused before anything is diffed, never half
// used.
export function checkSnapshot(v: unknown, engine: Engine, database: string): Snapshot {
  const o = object(v, 'schema');
  const tables = array(o.tables, 'tables').map((t) => checkTable(t));
  const seen = new Set<string>();
  for (const t of tables) {
    if (seen.has(t.name)) throw bad(`There are two tables called ${t.name}.`);
    seen.add(t.name);
  }
  tables.sort((a, b) => a.name.localeCompare(b.name));
  return { engine, database, tables, notes: array(o.notes ?? [], 'notes').map((n) => String(n).slice(0, 200)) };
}

export function checkTable(v: unknown): Table {
  const o = object(v, 'table');
  const name = ident(o.name, 'table');
  const columns = array(o.columns, `${name}'s fields`).map((c) => checkColumn(c, name));
  if (columns.length === 0) throw bad(`${name} needs at least one field.`);
  const seen = new Set<string>();
  for (const c of columns) {
    if (seen.has(c.name)) throw bad(`${name} has two fields called ${c.name}.`);
    seen.add(c.name);
  }
  const has = (col: string, where: string) => {
    if (!seen.has(col)) throw bad(`${name} has no field called ${col}, so ${where} cannot use it.`);
    return col;
  };
  const primaryKey = array(o.primaryKey ?? [], `${name}'s primary key`)
    .map((c) => has(ident(c, 'field'), 'the primary key'));
  const uniques = array(o.uniques ?? [], `${name}'s unique fields`).map((u) => {
    const uo = object(u, 'unique');
    return {
      name: ident(uo.name, 'unique'),
      columns: array(uo.columns, 'unique').map((c) => has(ident(c, 'field'), 'that must-be-different rule')),
    };
  });
  const foreignKeys = array(o.foreignKeys ?? [], `${name}'s relationships`).map((f) => {
    const fo = object(f, 'relationship');
    const ref = object(fo.references, 'relationship');
    const onDelete = fo.onDelete === 'cascade' || fo.onDelete === 'set null' ? fo.onDelete : 'restrict';
    return {
      name: ident(fo.name, 'relationship'),
      columns: array(fo.columns, 'relationship').map((c) => has(ident(c, 'field'), 'that relationship')),
      references: {
        table: ident(ref.table, 'table'),
        columns: array(ref.columns, 'relationship').map((c) => ident(c, 'field')),
      },
      onDelete,
    } as ForeignKey;
  });
  const indexes = array(o.indexes ?? [], `${name}'s indexes`).map((i) => {
    const io = object(i, 'index');
    return {
      name: ident(io.name, 'index'),
      columns: array(io.columns, 'index').map((c) => ident(c, 'field')),
      unique: io.unique === true,
    };
  });
  // An identity column is the engine filling a number in. It has to be a whole
  // number and it has to be the key, or the engine would refuse it anyway --
  // better to say which in her words than to let MariaDB say 1075.
  for (const c of columns) {
    if (!c.identity) continue;
    if (c.type !== 'integer') throw bad(`${name}.${c.name} fills itself in, so it has to be a whole number.`);
    if (!primaryKey.includes(c.name)) throw bad(`${name}.${c.name} fills itself in, so it has to be the primary key.`);
  }
  const table: Table = { name, columns, primaryKey, uniques, foreignKeys, indexes };
  if (o.was !== undefined && o.was !== null) table.was = ident(o.was, 'table');
  return table;
}

export function checkColumn(v: unknown, table: string): Column {
  const o = object(v, 'field');
  const name = ident(o.name, 'field');
  if (!isColumnType(o.type)) throw bad(`${table}.${name} has a kind of field the panel does not know.`);
  const type = o.type;
  const column: Column = {
    name,
    type,
    sqlType: typeof o.sqlType === 'string' ? o.sqlType.slice(0, 120) : null,
    required: o.required === true,
    default: checkDefault(o.default, type, `${table}.${name}`),
  };
  if (type === 'short_text') {
    const n = Number(o.length ?? 255);
    if (!Number.isInteger(n) || n < 1 || n > 4000) throw bad(`${table}.${name}: a short text field can be 1 to 4000 characters long.`);
    column.length = n;
  }
  if (type === 'decimal') {
    const p = Number(o.precision ?? 12);
    const s = Number(o.scale ?? 2);
    if (!Number.isInteger(p) || p < 1 || p > 38) throw bad(`${table}.${name}: a decimal number can keep 1 to 38 digits.`);
    if (!Number.isInteger(s) || s < 0 || s > p) throw bad(`${table}.${name}: the digits after the point have to fit inside the digits it keeps.`);
    column.precision = p;
    column.scale = s;
  }
  if (o.was !== undefined && o.was !== null) column.was = ident(o.was, 'field');
  if (o.identity === true) column.identity = true;
  if (type === 'other' && !column.sqlType) throw bad(`${table}.${name} says it is something else, but not what.`);
  return column;
}

function checkDefault(v: unknown, type: ColumnType, where: string): ColumnDefault | null {
  if (v === null || v === undefined) return null;
  const o = object(v, 'default');
  switch (o.kind) {
    case 'none': return { kind: 'none' };
    case 'now':
      if (type !== 'date' && type !== 'time' && type !== 'timestamptz') {
        throw bad(`${where}: "now" only makes sense for a date or a time.`);
      }
      return { kind: 'now' };
    case 'text': {
      const value = typeof o.value === 'string' ? o.value : '';
      if (!DEFAULT_TEXT_RE.test(value)) {
        throw bad(`${where}: a starting value can be up to 100 letters, digits and ordinary punctuation. Quotes and backslashes are not allowed.`);
      }
      return { kind: 'text', value };
    }
    case 'number': {
      const value = Number(o.value);
      if (!Number.isFinite(value)) throw bad(`${where}: that starting value is not a number.`);
      return { kind: 'number', value };
    }
    case 'boolean': return { kind: 'boolean', value: o.value === true };
    // Only ever something introspect put there. It survives a round trip
    // through the browser unchanged and is refused by the printers, so the worst
    // a wrong one can do is stop that field being changed.
    case 'raw': return { kind: 'raw', sql: String(o.sql ?? '').slice(0, 200) };
    default: throw bad(`${where}: the panel does not know that kind of starting value.`);
  }
}

// ------------------------------------------------------------------ small checks

const bad = (message: string) => new PammyDbError('invalid', message);

function object(v: unknown, what: string): Record<string, unknown> {
  if (!v || typeof v !== 'object' || Array.isArray(v)) throw bad(`The panel sent a ${what} it cannot read.`);
  return v as Record<string, unknown>;
}

function array(v: unknown, what: string): unknown[] {
  if (!Array.isArray(v)) throw bad(`The panel sent a ${what} it cannot read.`);
  if (v.length > 2000) throw bad(`That is more than the panel will take in one go (${what}).`);
  return v;
}

// The same rule as a database name, for every table, column, constraint and
// index name (docs/studio-plan.md, "identifiers are checked twice"). The panel
// checks it so she gets a sentence; this is the check that has to hold.
function ident(v: unknown, what: string): string {
  if (typeof v !== 'string' || !NAME_RE.test(v)) {
    throw bad(`That ${what} name has characters the database will not take. Use lowercase letters, digits and underscores, starting with a letter.`);
  }
  return v;
}

// Why a table or field can't be called that, in her words, or null if it can.
// The page says this while she types; the helper refuses with the sentence above.
export function newIdentProblem(name: unknown, what: 'table' | 'field'): string | null {
  if (typeof name !== 'string' || name === '') return `Please type a ${what} name.`;
  if (name.length > 63) return 'Names can be at most 63 characters.';
  if (/[A-Z]/.test(name)) return 'Use lowercase letters only.';
  if (/^[0-9]/.test(name)) return 'Names have to start with a letter.';
  if (!NAME_RE.test(name)) return 'Use only lowercase letters, digits and underscores, starting with a letter.';
  return null;
}

// ------------------------------------------------------------------ drift

// What the draft was built from, in one string. Two snapshots of the same
// database hash the same only if every table, field, key and rule in them
// matches -- which is the whole question drift asks (docs/databases-plan.md 8).
// Notes are left out on purpose: "this table is not visible to the panel" is
// about the connection, not about the schema.
export function snapshotHash(s: Snapshot): string {
  return createHash('sha256').update(canonical({ ...s, notes: [] })).digest('hex').slice(0, 32);
}

// JSON with the keys in a settled order, so a hash is about the content and not
// about which route happened to build the object.
export function canonical(v: unknown): string {
  if (v === null || typeof v !== 'object') return JSON.stringify(v ?? null);
  if (Array.isArray(v)) return `[${v.map(canonical).join(',')}]`;
  const o = v as Record<string, unknown>;
  const keys = Object.keys(o).filter((k) => o[k] !== undefined).sort();
  return `{${keys.map((k) => `${JSON.stringify(k)}:${canonical(o[k])}`).join(',')}}`;
}

